# The PLCnext binding: every call on fixed size values as an IEC function of the PLCnext library Rant,
# managed C# over a native class RantMath whose C++ copies the values in and out of IEC memory.
import json
import textwrap

from csharp_backend import pascal
from model import short

GEN_CS = "// Generated by tools/bindgen/gen.py from src/, do not edit.\n"
GEN_CPP = "// Generated by tools/bindgen/gen.py from src/, do not edit.\n"

# C type to C# type and IEC type.
SCALARS = {
    "double": ("double", "LREAL"), "float": ("float", "REAL"), "int": ("int", "DINT"), "int8_t": ("sbyte", "SINT"),
    "uint8_t": ("byte", "USINT"), "int16_t": ("short", "INT"), "uint16_t": ("ushort", "UINT"),
    "int32_t": ("int", "DINT"), "uint32_t": ("uint", "UDINT"), "int64_t": ("long", "LINT"),
    "uint64_t": ("ulong", "ULINT"),
}

# The folder under Math in Engineer's library sidebar that each header's calls go in.
FOLDERS = {
    "vector.h": "Vectors", "rotation.h": "Rotations", "pose.h": "Poses", "matrix.h": "Matrices", "line.h": "Lines",
    "solid.h": "Solids", "region.h": "Regions", "motion.h": "Motion", "axes.h": "Axes", "camera.h": "Camera",
    "color.h": "Color", "geo.h": "Geo",
}

# Names ST keeps for itself, and the pin each C name becomes instead.
PINS = {"to": "Target", "from": "Source", "out": "Result", "return": "Result"}


def fixed(m, t):
    """Whether a value of type t has one size, so IEC holds it as it is."""
    if t in SCALARS or t in m.enums:
        return True
    s = m.structs.get(t)
    return s is not None and all(not f.pointer and fixed(m, f.type) for f in s.fields)


def fits(m, f):
    """A call whose every input and output is one value of a fixed size."""
    return (not f.hand
            and all(i.kind in ("value", "ref") and fixed(m, i.type) for i in f.inputs)
            and all(o.kind in ("return", "out") and fixed(m, o.type) for o in f.outputs))


def calls(m):
    return [f for f in m.functions if fits(m, f)]


def cs(t):
    return SCALARS[t][0] if t in SCALARS else short(t)


def pin(name):
    return PINS.get(name, pascal(name))


def natives_order(f):
    """The values the native call takes, in order: the answer first, then each C argument."""
    ret = [o for o in f.outputs if o.kind == "return"]
    order = [("out", ret[0])] if ret else []
    for a in f.args:
        order.append(("out" if a.kind == "out" else "in", a.a))
    return order


def own_types(m, used):
    out = []
    for e in m.own_enums():
        if e.name not in used:
            continue
        names = e.option_names()
        out.append(f"    [Enumeration]\n    public enum {e.short} : int\n    {{\n"
                   + "\n".join(f"        {n} = {v}," for n, (_, v) in zip(names, e.options)) + "\n    }\n")
    for s in m.own_structs():
        if s.name not in used:
            continue
        lines = []
        for fl in s.fields:
            if fl.type in SCALARS:
                lines.append(f"        [DataType(\"{SCALARS[fl.type][1]}\")]")
            lines.append(f"        public {cs(fl.type)} {fl.name};")
        out.append(f"    [Structure]\n    public struct {s.short}\n    {{\n" + "\n".join(lines) + "\n    }\n")
    return "\n".join(out)


def used_types(m, fs):
    seen = set()

    def visit(t):
        if t in seen:
            return
        seen.add(t)
        for fl in getattr(m.structs.get(t), "fields", []):
            visit(fl.type)
    for f in fs:
        for v in f.inputs + f.outputs:
            visit(v.type)
    return seen


def summary(text, indent):
    if not text:
        return ""
    words = text.replace("&", "and").replace("<", "under").replace(">", "over")
    return indent + "/// <summary>" + f"\n{indent}/// ".join(textwrap.wrap(words, 96)) + "</summary>\n"


def native_decl(f):
    args = ", ".join(f"UIntPtr {pin(v.name)}" for _, v in natives_order(f))
    if f.errors == "none":
        return f"        public static void {pascal(f.name)}({args})\n        {{\n        }}\n"
    return f"        public static bool {pascal(f.name)}({args})\n        {{\n            return false;\n        }}\n"


def data_type(t):
    return f", DataType(\"{SCALARS[t][1]}\")" if t in SCALARS and t not in ("double", "float", "int") else ""


def is_function(f):
    """An IEC function takes at least one input and has one return value and no other output."""
    return bool(f.inputs) and (f.errors == "bool" or (f.errors == "none" and len(f.outputs) == 1))


def native_call(f, value):
    """The native call, value naming the local or pin that holds each input and output."""
    args = ", ".join(f"(UIntPtr)(&{value(v)})" for _, v in natives_order(f))
    return f"RantMath.{pascal(f.name)}({args})"


def function(f, m):
    # Engineer passes a struct to a function and back by reference, so a struct is a ref parameter
    # here, and the C call reads a copy since a ref parameter has no fixed address.
    name = pascal(f.name)
    ans = f.outputs[0] if f.outputs else None
    by_ref = lambda t: t in m.structs
    params = [f"[Input{data_type(i.type)}] {'ref ' if by_ref(i.type) else ''}{cs(i.type)} {pin(i.name)}" for i in f.inputs]
    body = [f"{cs(i.type)} {pin(i.name).lower()} = {pin(i.name)};" for i in f.inputs if by_ref(i.type)]
    local = lambda v: "answer" if v is ans else pin(v.name).lower() if by_ref(v.type) else pin(v.name)
    value = cs(ans.type) if ans else "bool"
    if ans is None:
        body.append(f"return {native_call(f, local)};")
    else:
        body += [f"{cs(ans.type)} answer = new {cs(ans.type)}();", native_call(f, local) + ";"]
        if by_ref(ans.type):
            params.insert(0, f"[Output] ref {cs(ans.type)} {name}")
            body.append(f"{name} = answer;")
            value = "void"
        else:
            body.append("return answer;")
    return (summary(f.doc, "    ") + f"    [Function{data_type(ans.type) if ans else ''}]\n"
            f"    public static class {name}\n    {{\n        [Execution]\n"
            f"        public static unsafe {value} __Process({', '.join(params)})\n        {{\n"
            + "".join(f"            {line}\n" for line in body) + "        }\n    }\n")


def block(f):
    """Any other call: a function block with an output for each answer, and Ok, or Found for a
    call that may find nothing."""
    flag = {"throw": "Ok", "optional": "Found"}.get(f.errors)
    fields = [f"        [Input{data_type(i.type)}]\n        public {cs(i.type)} {pin(i.name)};" for i in f.inputs]
    fields += [f"        [Output{data_type(o.type)}]\n        public {cs(o.type)} {pin(o.name)};" for o in f.outputs]
    if flag:
        fields.append(f"        [Output]\n        public bool {flag};")
    body = [f"{cs(v.type)} {pin(v.name).lower()} = {pin(v.name) if v in f.inputs else f'new {cs(v.type)}()'};"
            for v in f.inputs + f.outputs]
    call = native_call(f, lambda v: pin(v.name).lower())
    body.append(f"{flag} = {call};" if flag else call + ";")
    body += [f"{pin(o.name)} = {pin(o.name).lower()};" for o in f.outputs]
    return (summary(f.doc, "    ") + f"    [FunctionBlock]\n    public class {pascal(f.name)}\n    {{\n"
            + "\n".join(fields) + "\n\n        [Initialization]\n        public void __Init()\n        {\n        }\n\n"
            "        [Execution]\n        public unsafe void __Process()\n        {\n"
            + "".join(f"            {line}\n" for line in body) + "        }\n    }\n")


def csharp(m):
    fs = calls(m)
    return (GEN_CS + "// Rant Math's calls on fixed size values as IEC functions, each over the native RantMath.\n"
            "using System;\nusing System.Iec61131Lib;\nusing Eclr;\nusing Iec61131.Engineering.Prototypes.Common;\n"
            "using Iec61131.Engineering.Prototypes.Methods;\nusing Iec61131.Engineering.Prototypes.Types;\n"
            "using Iec61131.Engineering.Prototypes.Variables;\n\nnamespace Rant\n{\n"
            + own_types(m, used_types(m, fs)) + "\n"
            "    // The C calls behind the functions, each value passed by its address.\n"
            "    [Native]\n    public class RantMath\n    {\n" + "\n".join(native_decl(f) for f in fs) + "    }\n\n"
            + "\n".join(function(f, m) if is_function(f) else block(f) for f in fs) + "}\n")


def native_body(f):
    order = natives_order(f)
    lines, c_args = [], []
    for k, (way, v) in enumerate(order):
        if way == "in":
            lines.append(f"const auto v{k} = In<{v.type}>(p{k});")
        elif v.kind != "return":
            lines.append(f"{v.type} v{k}{{}};")
    for k, (way, v) in enumerate(order):
        if v.kind == "return":
            continue
        c_args.append(f"&v{k}" if way == "out" or v.kind == "ref" else f"v{k}")
    call = f"{f.c}({', '.join(c_args)})"
    ret = next((k for k, (_, v) in enumerate(order) if v.kind == "return"), None)
    if f.errors == "throw":
        lines.append(f"const bool ok = {call} == RANT_MATH_OK;")
    elif f.errors != "none":
        lines.append(f"const bool ok = {call} != 0;")
    elif ret is not None:
        lines.append(f"Out(p{ret}, {call});")
    else:
        lines.append(call + ";")
    lines += [f"Out(p{k}, v{k});" for k, (way, v) in enumerate(order) if way == "out" and v.kind != "return"]
    if f.errors != "none":
        lines.append("return ok;")
    params = ", ".join(f"UIntPtr p{k}" for k in range(len(order)))
    kind = "void" if f.errors == "none" else "Boolean"
    return (f"{kind} __PInvoke__ Rant::RantMath::{pascal(f.name)}({params})\n{{\n"
            + "".join(f"    {line}\n" for line in lines) + "}\n")


# What each scalar takes in IEC memory, which lays a struct out as C does: each field at its own alignment.
SIZES = {"double": 8, "float": 4, "int": 4, "int8_t": 1, "uint8_t": 1, "int16_t": 2, "uint16_t": 2, "int32_t": 4,
         "uint32_t": 4, "int64_t": 8, "uint64_t": 8}


def iec_layout(m, t):
    """The size and alignment of type t in IEC memory."""
    if t in SIZES:
        return SIZES[t], SIZES[t]
    if t in m.enums:
        return 4, 4
    offset, align = 0, 1
    for fl in m.structs[t].fields:
        size, a = iec_layout(m, fl.type)
        count = 1
        for d in fl.dims:
            count *= d
        offset = -(-offset // a) * a + size * count
        align = max(align, a)
    return -(-offset // align) * align, align


def size_checks(m):
    """Each struct the natives copy by its C size, held to the size IEC memory gives it."""
    structs = sorted(t for t in used_types(m, calls(m)) if t in m.structs)
    return "".join(f'static_assert(sizeof({t}) == {iec_layout(m, t)[0]}, "{t} is not the size of its IEC type");\n' for t in structs) + "\n"


def cpp(m):
    return (GEN_CPP + "// The native side of RantMath: each value copied out of IEC memory, which keeps no C alignment,\n"
            "// through the C call and back.\n"
            '#include "eclr.h"\n#include "Rant.h"\n\n#include "rant_math.h"\n\n#include <cstring>\n\nnamespace {\n\n'
            "template <typename T> T In(UIntPtr p)\n{\n    T v;\n    std::memcpy(&v, reinterpret_cast<const void*>(p), sizeof v);\n"
            "    return v;\n}\n\ntemplate <typename T> void Out(UIntPtr p, const T& v)\n{\n"
            "    std::memcpy(reinterpret_cast<void*>(p), &v, sizeof v);\n}\n\n} // namespace\n\n"
            + size_checks(m)
            + "\n".join(native_body(f) for f in calls(m))
            + "\nRant::RantMath::RantMath()\n{\n}\n\nvoid __PInvoke__ Rant::RantMath::ctor()\n{\n"
            "    new (this) Rant::RantMath();\n}\n")


def folders(m):
    """Each call's name by the folder the library's sidebar shows it in: its header's, and in that a
    folder of the type its name starts with when that type has more than one call there. A header
    whose calls all take one type keeps them in its own folder."""
    types = sorted((s[4:] for s in m.structs), key=len, reverse=True)
    groups = {}
    for f in calls(m):
        name = pascal(f.name)
        header = FOLDERS.get(f.header, f.header.removesuffix(".h").capitalize())
        groups.setdefault(header, []).append((next((t for t in types if name.startswith(t)), ""), name))
    out = {}
    for header, named in groups.items():
        one = len({t for t, _ in named}) == 1
        for t, name in named:
            many = t and not one and sum(1 for o, _ in named if o == t) > 1
            out.setdefault(f"{header}/{t}" if many else header, []).append(name)
    return json.dumps(out, indent=2) + "\n"


def generate(m):
    return [("bindings/plcnext/RantMath.cs", csharp(m)), ("bindings/plcnext/rant_math_natives.inc", cpp(m)),
            ("bindings/plcnext/RantMath.json", folders(m))]

# The C++ binding: the calls of rant_math.hpp, and the table of thunks its vector test replays.
import textwrap

from model import HIDDEN_STRUCTS

GEN = "/* Generated by tools/bindgen/gen.py from src/, do not edit. */\n"

CPP_SCALARS = {"double", "float", "int", "int8_t", "uint8_t", "int16_t", "uint16_t", "int32_t", "uint32_t",
               "int64_t", "uint64_t", "size_t"}


def short(t):
    return t[4:] if t.startswith("Rant") else t


def type_of(t):
    return t if t in CPP_SCALARS else short(t)


def to_c(m, t, expr):
    if t in CPP_SCALARS:
        return expr
    if t in m.enums:
        return f"static_cast<detail::{t}>({expr})"
    return f"impl::bits<detail::{t}>({expr})"


def from_c(m, t, expr):
    if t in CPP_SCALARS:
        return expr
    if t in m.enums:
        return f"static_cast<{short(t)}>({expr})"
    return f"impl::bits<{short(t)}>({expr})"


def out_ptr(t, expr):
    return expr if t in CPP_SCALARS else f"impl::mut<detail::{t}>({expr})"


def input_decl(i, fn):
    k = i.kind
    default = ""
    if k in ("value",):
        return f"{type_of(i.type)} {i.name}"
    if k == "ref":
        return f"const {type_of(i.type)} &{i.name}"
    if k == "opt_ref":
        return f"const {type_of(i.type)} *{i.name}"
    if k == "list":
        return f"Span<const {type_of(i.type)}> {i.name}"
    if k == "string":
        return f"const char *{i.name}"
    if k == "prism":
        return f"const Prism &{i.name}"
    if k == "shape":
        return f"const Shape &{i.name}"
    if k == "shape2d":
        return f"const Shape2D &{i.name}"
    if k == "image":
        return f"const ImageView &{i.name}"
    if k == "image_mut":
        return f"MutableImageView {i.name}"
    if k == "cloud":
        return f"const PointCloudView &{i.name}"
    if k == "cloud_mut":
        return f"MutablePointCloudView {i.name}"
    if k == "grid":
        return f"const Grid &{i.name}"
    if k == "grid_mut":
        return f"Grid &{i.name}"
    if k == "scan":
        return f"const LaserScan &{i.name}"
    if k == "det2d":
        return f"Span<const Detection2D> {i.name}"
    if k == "det3d":
        return f"Span<const Detection3D> {i.name}"
    if k == "matrix":
        return f"const Matrix &{i.name}"
    if k == "fit_options":
        return f"const FitOptions &{i.name} = {{}}"
    if k == "align_options":
        return f"const AlignOptions &{i.name} = {{}}"
    if k == "tree":
        return f"const KdTree &{i.name}"
    raise KeyError(k)


def output_type(o):
    k = o.kind
    if k in ("return", "out"):
        return "const char *" if o.type == "string" else type_of(o.type)
    if k == "fixed":
        return f"std::array<{type_of(o.type)}, {o.size}>"
    if k in ("query", "sized", "same", "expr", "room"):
        return f"std::vector<{type_of(o.type)}>"
    if k == "matrix":
        return "Matrix"
    if k in ("image", "image_copy"):
        return "Image"
    if k in ("cloud_layout", "cloud_select"):
        return "PointCloud"
    if k == "field":
        return "std::optional<PointField>"
    if k == "prism":
        return "Prism"
    if k == "handle":
        return "KdTree"
    if k == "shape_new":
        return short(o.type)
    raise KeyError(k)


def result_type(f):
    outs = [o for o in f.outputs if o.kind != "mutated"]
    if not outs:
        return "bool" if f.errors == "bool" else "void"
    if len(outs) == 1:
        t = output_type(outs[0])
    else:
        t = "std::tuple<" + ", ".join(output_type(o) for o in outs) + ">"
    if f.errors == "optional":
        return f"std::optional<{t}>"
    return t


def size_word(words, f):
    # The rows, columns or size of an output, in terms of the inputs.
    if words == "min":
        return "(a.rows < a.cols ? a.rows : a.cols)"
    return words


class Writer:
    def __init__(self, m, f):
        self.m, self.f = m, f
        self.lines = []
        self.outs = {id(o): f"o{j}" for j, o in enumerate(f.outputs)}

    def emit(self, line):
        self.lines.append("    " + line)

    def c_arg(self, a, asking):
        k = a.kind
        m = self.m
        if k == "value":
            return to_c(m, a.a.type, a.a.name)
        if k == "ref":
            return f"impl::mut<const detail::{a.a.type}>(&{a.a.name})"
        if k == "opt_ref":
            return f"impl::mut<const detail::{a.a.type}>({a.a.name})"
        if k == "list_ptr":
            if a.a.type in CPP_SCALARS:
                return f"{a.a.name}.data()"
            return f"impl::ptr<detail::{a.a.type}>({a.a.name})"
        if k == "list_count":
            return f"impl::count({a.a.name}, {a.b.name})" if a.b else f"impl::count({a.a.name}.size())"
        if k == "degree":
            return f"impl::count({a.a.name}.size() - 1)"
        if k == "view":
            return f"impl::view<detail::{a.b}, detail::{a.a.type}>({a.a.name})"
        if k == "mesh":
            return f"impl::mesh({a.a.name}, {a.b.name})"
        if k == "prism":
            return f"impl::prism({a.a.name})"
        if k == "matrix":
            return f"impl::matrix({a.a.name})"
        if k == "shape" or k == "shape2d":
            return f"{a.a.name}.raw()"
        if k == "image":
            return f"&c_{a.a.name}"
        if k == "image_mut":
            return f"&c_{a.a.name}"
        if k == "cloud":
            return f"{a.a.name}.raw()"
        if k == "cloud_mut":
            return f"{a.a.name}.raw()"
        if k in ("grid",):
            return f"&c_{a.a.name}.raw"
        if k == "grid_mut":
            return f"&c_{a.a.name}.raw"
        if k == "scan":
            return f"&c_{a.a.name}"
        if k == "det_ptr":
            return f"c_{a.a.name}.data()"
        if k == "det_count":
            return f"impl::count(c_{a.a.name}.size())"
        if k == "string":
            return a.a.name
        if k == "fit_options" or k == "align_options":
            return f"&c_{a.a.name}"
        if k == "tree":
            return f"{a.a.name}.raw()"
        if k == "out":
            o = a.a
            name = self.outs[id(o)]
            if o.kind == "handle":
                return "&tree"
            if o.kind == "image_copy":
                return f"&{name}"
            if o.kind == "cloud_select":
                return "nullptr" if asking else f"{name}.data.data()"
            if o.kind == "query" and asking:
                return "nullptr"
            if o.kind == "out":
                return out_ptr(o.type, "&" + name)
            return out_ptr(o.type, name + ".data()")
        if k == "count_ptr":
            o = a.a
            return "&n0" if o.kind == "room" else f"&n{self.f.outputs.index(o)}"
        if k == "matrix_out":
            return f"impl::matrix({self.outs[id(a.a)]})"
        if k == "image_out":
            return f"&c_{self.outs[id(a.a)]}"
        raise KeyError(k)

    def call(self, asking=False):
        args = ", ".join(self.c_arg(a, asking) for a in self.f.args)
        return f"detail::{self.f.c}({args})"

    def declare_inputs(self):
        for i in self.f.inputs:
            k = i.kind
            if k in ("image", "image_mut"):
                self.emit(f"detail::RantImageView c_{i.name} = impl::image({i.name});")
            elif k in ("grid", "grid_mut"):
                self.emit(f"impl::GridRef c_{i.name}({i.name});")
            elif k == "scan":
                self.emit(f"detail::RantLaserScanView c_{i.name} = impl::scan({i.name});")
            elif k == "det2d":
                self.emit(f"std::vector<detail::RantDetection2DView> c_{i.name} = impl::detections<detail::RantDetection2DView>({i.name});")
            elif k == "det3d":
                self.emit(f"std::vector<detail::RantDetection3DView> c_{i.name} = impl::detections<detail::RantDetection3DView>({i.name});")
            elif k == "fit_options":
                points = self.f.inputs[0].name
                self.emit(f"detail::RantFitOptions c_{i.name} = impl::fit({i.name}, {points}.size());")
            elif k == "align_options":
                self.emit(f"detail::RantAlignOptions c_{i.name} = impl::align({i.name}, source.size(), target.size());")
            elif i.kind == "list" and self.f.c == "rant_polynomial_at":
                self.emit(f"if ({i.name}.empty()) impl::argument();")
            elif i.kind == "list" and i.type == "uint8_t" and self.f.c == "rant_point_cloud_select":
                self.emit(f"if ({i.name}.size() != {self.f.inputs[0].name}.raw()->size / ({self.f.inputs[0].name}.raw()->point_step ? {self.f.inputs[0].name}.raw()->point_step : 1)) impl::argument();")

    def declare_outputs(self):
        for j, o in enumerate(self.f.outputs):
            k = o.kind
            name = f"o{j}"
            if k == "out":
                self.emit(f"{type_of(o.type)} {name}{{}};")
            elif k == "fixed":
                self.emit(f"std::array<{type_of(o.type)}, {o.size}> {name}{{}};")
            elif k == "same":
                self.emit(f"std::vector<{type_of(o.type)}> {name}({o.size.name}.size());")
            elif k == "sized":
                self.emit(f"std::vector<{type_of(o.type)}> {name}({o.size.name});")
            elif k == "expr":
                self.emit(f"std::vector<{type_of(o.type)}> {name}(size_t({size_word(o.size, self.f)}));")
            elif k == "room":
                self.emit(f"std::vector<{type_of(o.type)}> {name}({o.size.name});")
            elif k == "matrix":
                self.emit(f"Matrix {name} = impl::matrix_out({size_word(o.rows, self.f)}, {size_word(o.cols, self.f)});")
            elif k == "image":
                self.emit(f"Image {name} = impl::image_out({self.image_word(o.size)}, {self.image_word(o.cols)}, {self.image_word(o.rows)});")
                self.emit(f"detail::RantImageView c_{name} = impl::image(MutableImageView({name}));")
            elif k == "image_copy":
                self.emit(f"detail::RantImageView {name}{{}};")
            elif k == "handle":
                self.emit("detail::RantKdTree *tree = nullptr;")

    def image_word(self, word):
        words = {
            "turned_width": "impl::turned_width(src, quarter_turns)",
            "turned_height": "impl::turned_height(src, quarter_turns)",
            "ideal_width": "(ideal ? ideal : &camera)->width",
            "ideal_height": "(ideal ? ideal : &camera)->height",
        }
        return words.get(word, word)

    def answer(self):
        f = self.f
        parts = []
        for j, o in enumerate(f.outputs):
            k = o.kind
            name = f"o{j}"
            if k == "mutated":
                continue
            if k == "return":
                parts.append("r" if o.type == "string" else from_c(self.m, o.type, "r"))
            elif k == "image_copy":
                parts.append(f"impl::image_copy({name})")
            elif k == "handle":
                parts.append("KdTree(tree)")
            elif k == "prism":
                parts.append("impl::prism_of(r)")
            elif k == "cloud_layout":
                parts.append("impl::cloud_like(r)")
            elif k == "field":
                parts.append("field")
            elif k == "shape_new":
                parts.append("r")
            else:
                parts.append(f"std::move({name})" if k not in ("out", "fixed") else name)
        if not parts:
            return None
        if len(parts) == 1:
            return parts[0].replace("std::move(o0)", "o0")
        return "{ " + ", ".join(parts) + " }"

    def body(self):
        f = self.f
        if f.c.startswith("rant_shape_from_") or f.c.startswith("rant_shape2d_from_"):
            return self.shape_body()
        if f.c == "rant_point_cloud_field":
            return self.field_body()
        if f.c == "rant_point_cloud_select":
            return self.select_body()
        self.declare_inputs()
        self.declare_outputs()
        asked = [o for o in f.outputs if o.kind == "query" and not hasattr(o.size, "kind")]
        rooms = [o for o in f.outputs if o.kind == "room"]
        if asked:
            for o in asked:
                self.emit(f"uint32_t n{f.outputs.index(o)} = 0;")
            self.emit(f"impl::room({self.call(True)});")
            for j, o in enumerate(f.outputs):
                if o.kind == "query":
                    n = f.outputs.index(o.size) if hasattr(o.size, "kind") else j
                    self.emit(f"std::vector<{type_of(o.type)}> o{j}({self.items(n, o)});")
        if rooms:
            self.emit(f"uint32_t n0 = {rooms[0].size.name};")
        call = self.call()
        ans = self.answer()
        ret = f.ret
        if ret == "RantMathResult":
            self.emit(f"impl::check({call});")
        elif ret == "int":
            if f.outputs:
                self.emit(f"if (!{call}) return std::nullopt;")
            else:
                self.emit(f"return {call} != 0;")
                return
        elif ret == "void":
            self.emit(f"{call};")
        elif f.outputs and f.outputs[0].kind in ("return", "prism", "cloud_layout") or any(o.kind == "return" for o in f.outputs):
            self.emit(f"auto r = {call};")
        else:
            self.emit(f"{call};")
        for j, o in enumerate(f.outputs):
            if o.kind == "query":
                n = f.outputs.index(o.size) if hasattr(o.size, "kind") else j
                self.emit(f"o{j}.resize({self.items(n, o)});")
            elif o.kind == "room":
                self.emit(f"o{j}.resize(n0);")
        if ans:
            self.emit(f"return {result_type(f)}{ans};" if ans.startswith("{") else f"return {ans};")

    def items(self, n, o):
        return f"size_t(n{n}) * {o.per}" if o.per != 1 else f"n{n}"

    def shape_body(self):
        f = self.f
        word = f.c.split("_from_")[1]
        i = f.inputs[0]
        two = f.ret == "RantShape2D"
        cls = "Shape2D" if two else "Shape"
        kinds = {"polyline": "detail::RANT_SHAPE_POLYLINE", "polygon": "detail::RANT_SHAPE_POLYGON",
                 "polygon2d": "detail::RANT_SHAPE2D_POLYGON", "polyline2d": "detail::RANT_SHAPE2D_POLYLINE"}
        if word in kinds:
            self.emit(f"return {cls}::polyline({i.name}, {kinds[word]});")
        elif word == "mesh":
            self.emit(f"return Shape::mesh({f.inputs[0].name}, {f.inputs[1].name});")
        elif word == "prism":
            self.emit(f"return Shape::prism({i.name});")
        else:
            self.emit(f"return {cls}::plain(detail::{f.c}({to_c(self.m, i.type, i.name)}));")

    def field_body(self):
        self.emit("const detail::RantPointFieldView *found = detail::rant_point_cloud_field(cloud.raw(), name);")
        self.emit("if (!found) return std::nullopt;")
        self.emit("return impl::fields_of(found, 1)[0];")

    def select_body(self):
        self.emit("const detail::RantPointCloudView &c = *cloud.raw();")
        self.emit("impl::check(detail::rant_point_cloud_check(&c));")
        self.emit("if (keep.size() != c.size / c.point_step) impl::argument();")
        self.emit("uint32_t n = 0;")
        self.emit("impl::room(detail::rant_point_cloud_select(&c, keep.data(), nullptr, &n));")
        self.emit("PointCloud out = impl::cloud_like(c);")
        self.emit("out.data.resize(size_t(n) * c.point_step);")
        self.emit("impl::check(detail::rant_point_cloud_select(&c, keep.data(), out.data.data(), &n));")
        self.emit("return out;")


def function(m, f):
    w = Writer(m, f)
    w.body()
    args = ", ".join(input_decl(i, f) for i in f.inputs)
    head = f"inline {result_type(f)} {f.name}({args}) {{"
    doc = ""
    if f.doc:
        doc = "".join(f"/* {line} */\n" for line in textwrap.wrap(f.doc, 100))
    return doc + head + "\n" + "\n".join(w.lines) + "\n}\n"


def own_types(m):
    out = []
    for e in m.own_enums():
        names = e.option_names()
        out.append(f"enum class {e.short} : int {{\n" + ",\n".join(f"    {n} = {v}" for n, (_, v) in zip(names, e.options)) + "\n};\n")
    for s in m.own_structs():
        lines = []
        for fld in s.fields:
            t = type_of(fld.type)
            init = " = 0" if fld.type in CPP_SCALARS else ""
            lines.append(f"    {t} {fld.name}{init};")
        out.append(f"struct {s.short} {{\n" + "\n".join(lines) + "\n};\n")
    return "\n".join(out)


def api(m):
    parts = [GEN, own_types(m), ""]
    for f in m.functions:
        if f.hand:
            continue
        parts.append(function(m, f))
    return "\n".join(parts)


# The vector test: a thunk per function, turning JSON into inputs and the answer back into JSON.

def thunk_input(m, i, n):
    k = i.kind
    a = f"a[{n}]"
    if k in ("value", "ref"):
        return f"{type_of(i.type)} x{n} = get<{type_of(i.type)}>({a});"
    if k == "opt_ref":
        return f"std::optional<{type_of(i.type)}> x{n}o; if (!{a}.is_null()) x{n}o = get<{type_of(i.type)}>({a}); const {type_of(i.type)} *x{n} = x{n}o ? &*x{n}o : nullptr;"
    if k == "list":
        return f"std::vector<{type_of(i.type)}> x{n} = get_list<{type_of(i.type)}>({a});"
    if k == "string":
        return f"std::string x{n}s = {a}.str; const char *x{n} = x{n}s.c_str();"
    return {
        "prism": f"Prism x{n} = get_prism({a});",
        "shape": f"Shape x{n} = get_shape({a});",
        "shape2d": f"Shape2D x{n} = get_shape2d({a});",
        "image": f"Image x{n} = get_image({a});",
        "image_mut": f"Image x{n} = get_image({a});",
        "cloud": f"PointCloud x{n} = get_cloud({a});",
        "cloud_mut": f"PointCloud x{n} = get_cloud({a});",
        "grid": f"Grid x{n} = get_grid({a});",
        "grid_mut": f"Grid x{n} = get_grid({a});",
        "scan": f"LaserScan x{n} = get_scan({a});",
        "det2d": f"std::vector<Detection2D> x{n} = get_det2d({a});",
        "det3d": f"std::vector<Detection3D> x{n} = get_det3d({a});",
        "matrix": f"Matrix x{n} = get_matrix({a});",
        "fit_options": f"FitHolder x{n}h({a}, a[0].items.size()); const FitOptions &x{n} = x{n}h.options;",
        "align_options": f"AlignHolder x{n}h({a}, a[0].items.size(), a[1].items.size()); const AlignOptions &x{n} = x{n}h.options;",
        "tree": f"KdTree x{n} = kdtree_create(get_list<Double3>({a}.at(\"points\")));",
    }[k]


def thunk(m, f):
    lines = []
    for n, i in enumerate(f.inputs):
        lines.append("        " + thunk_input(m, i, n))
    args = ", ".join(f"x{n}" for n in range(len(f.inputs)))
    call = f"rant::math::{f.name}({args})"
    mutated = [o for o in f.outputs if o.kind == "mutated"]
    outs = [o for o in f.outputs if o.kind != "mutated"]
    if mutated:
        index = f.inputs.index(mutated[0].size)
        lines.append(f"        {call};")
        lines.append(f"        J out = put(x{index});")
    elif f.errors == "optional" and len(outs) > 1:
        raise ValueError(f.name)
    elif not outs and f.errors != "bool":
        lines.append(f"        {call};")
        lines.append("        J out;")
    else:
        lines.append(f"        J out = put({call});")
    for n, i in enumerate(f.inputs):
        if i.kind in ("fit_options", "align_options"):
            lines.append(f"        x{n}h.add_extras(out);")
    return "\n".join(lines)


def thunks(m):
    decls = []
    for s in m.used_structs():
        decls.append(f"template <> {s.short} get<{s.short}>(const J &j);")
        decls.append(f"J put(const {s.short} &v);")
    for e in m.used_enums():
        decls.append(f"template <> {e.short} get<{e.short}>(const J &j);")
        decls.append(f"J put({e.short} v);")
    rows = [GEN, "#if defined(THUNK_DECLS)"] + decls + ["#else"]
    conv = []
    seen = set()
    for s in m.used_structs():
        if s.name in seen:
            continue
        seen.add(s.name)
        t = s.short
        reads, writes = [], []
        for fld in s.fields:
            key = f'j.at("{fld.name}")'
            if fld.dims:
                reads.append(f"get_array(v.{fld.name}, {key});")
                writes.append(f'o.add("{fld.name}", put_array(v.{fld.name}));')
            else:
                if fld.type in m.structs:
                    ft = short(fld.type)
                    reads.append(f"v.{fld.name} = get<{ft}>({key});")
                elif s.name == "RantCameraIntrinsics" and fld.name == "model":
                    reads.append(f"v.{fld.name} = static_cast<DistortionModel>(uint64_t(get<double>({key})));")
                else:
                    reads.append(f"v.{fld.name} = static_cast<{'decltype(v.' + fld.name + ')'}>(get<double>({key}));")
                if s.name == "RantCameraIntrinsics" and fld.name == "model":
                    writes.append(f'o.add("{fld.name}", put(uint64_t(v.{fld.name})));')
                else:
                    writes.append(f'o.add("{fld.name}", put(v.{fld.name}));')
        conv.append(f"template <> {t} get<{t}>(const J &j) {{\n    {t} v{{}};\n    " + "\n    ".join(reads) + "\n    return v;\n}\n")
        conv.append(f"J put(const {t} &v) {{\n    J o = J::object();\n    " + "\n    ".join(writes) + "\n    return o;\n}\n")
    rows.append("\n".join(conv))
    for e in m.used_enums():
        rows.append(f"template <> {e.short} get<{e.short}>(const J &j) {{ return static_cast<{e.short}>(int(get<double>(j))); }}")
        rows.append(f"J put({e.short} v) {{ return put(int(v)); }}")
    rows.append("const std::map<std::string, Thunk> thunks = {")
    for f in m.functions:
        if not f.vector:
            continue
        body = thunk(m, f)
        rows.append(f'    {{"{f.name}", [](const std::vector<J> &a) {{\n        (void)a;\n{body}\n        return out;\n    }}}},')
    rows.append("};")
    rows.append("#endif")
    return "\n".join(rows) + "\n"



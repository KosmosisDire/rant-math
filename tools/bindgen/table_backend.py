# The library's table of itself, src/table.c: every call as the bindings see it, and each type's methods
# and operators, so any binding or tool reads one list.
GEN = "/* Generated by tools/bindgen/gen.py from src/, do not edit. */\n"


def short(t):
    return t[4:] if t.startswith("Rant") else t


def text(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def table_c(m):
    functions = [f for f in m.functions if not f.hand]
    index = {f.c: k for k, f in enumerate(functions)}
    args, rows = [], []
    for f in functions:
        first_in = len(args)
        args += [f"{{ {text(i.name)}, {text(i.kind)}, {text(short(i.type))} }}" for i in f.inputs]
        first_out = len(args)
        args += [f"{{ {text(o.name)}, {text(o.kind)}, {text(short(o.type))} }}" for o in f.outputs]
        rows.append(f"    {{ {text(f.name)}, {text(f.doc)}, i_table_args + {first_in}, {len(f.inputs)}, "
                    f"i_table_args + {first_out}, {len(f.outputs)}, {text(f.errors)} }},")
    methods = [f"    {{ {text(me.type)}, {text(me.name)}, {index[me.func.c]}, "
               f"{'UINT32_MAX' if me.static else me.self_index}, {text(me.field)} }}," for me in m.methods]
    operators = [f"    {{ {text(o.op)}, {text(o.left)}, {text(o.right)}, {index[o.func.c]}, {text(o.how)} }},"
                 for o in m.operators]

    def array(kind, name, items):
        return f"static const {kind} {name}[] = {{\n" + "\n".join(items) + "\n};\n"

    def reader(word, kind, name):
        count = f"(uint32_t)(sizeof {name} / sizeof {name}[0])"
        return (f"uint32_t rant_math_{word}_count(void){{ return {count}; }}\n"
                f"const {kind} *rant_math_{word}_at(uint32_t index){{ return index < {count} ? &{name}[index] : NULL; }}\n")

    return (GEN + '#include "table.h"\n\n'
            + array("RantMathArg", "i_table_args", ["    " + a + "," for a in args]) + "\n"
            + array("RantMathFunction", "i_table_functions", rows) + "\n"
            + array("RantMathMethod", "i_table_methods", methods) + "\n"
            + array("RantMathOperator", "i_table_operators", operators) + "\n"
            + reader("function", "RantMathFunction", "i_table_functions")
            + reader("method", "RantMathMethod", "i_table_methods")
            + reader("operator", "RantMathOperator", "i_table_operators"))


def generate(m):
    return [("src/table.c", table_c(m))]

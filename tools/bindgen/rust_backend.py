# The Rust binding: extern declarations and one safe function per C call.
import textwrap

GEN = "// Generated by tools/bindgen/gen.py from src/, do not edit.\n"

RUST_SCALARS = {
    "double": "f64", "float": "f32", "int": "i32", "int8_t": "i8", "uint8_t": "u8", "int16_t": "i16", "uint16_t": "u16",
    "int32_t": "i32", "uint32_t": "u32", "int64_t": "i64", "uint64_t": "u64", "size_t": "usize",
}
KEYWORDS = {"type", "ref", "in", "fn", "use", "box", "move", "match", "loop", "where", "final", "try", "do", "abstract", "virtual", "yield"}


def short(t):
    return t[4:] if t.startswith("Rant") else t


def name_of(n):
    return "r#" + n if n in KEYWORDS else n


def rs_type(m, t):
    return RUST_SCALARS.get(t) or short(t)


def raw_type(m, t):
    if t in RUST_SCALARS:
        return RUST_SCALARS[t]
    if t in m.enums:
        return "c_int"
    if t in RAW_VIEWS:
        return "Raw" + short(t)
    return short(t)


RAW_VIEWS = {
    "RantPolygonView", "RantPolygon2DView", "RantPolylineView", "RantPolyline2DView", "RantPathView", "RantPath2DView",
    "RantPrismView", "RantMeshView", "RantMatrixView", "RantImageView", "RantPointFieldView", "RantPointCloudView",
    "RantGridFieldView", "RantGridView", "RantLaserScanView", "RantDetection2DView", "RantDetection3DView",
    "RantFitOptions", "RantAlignOptions",
}


def raw_structs(m):
    out = []
    for t in sorted(RAW_VIEWS):
        s = m.structs[t]
        lines = []
        for f in s.fields:
            if f.pointer:
                mutable = f.type == "uint8_t" or (t == "RantMatrixView") or f.name == "error"
                kind = "*mut" if mutable else "*const"
                inner = "c_char" if f.type == "char" else raw_type(m, f.type)
                lines.append(f"    pub {name_of(f.name)}: {kind} {inner},")
            elif f.type in m.enums:
                lines.append(f"    pub {name_of(f.name)}: c_int,")
            else:
                lines.append(f"    pub {name_of(f.name)}: {raw_type(m, f.type)},")
        out.append(f"#[repr(C)]\n#[derive(Clone, Copy)]\npub struct Raw{short(t)} {{\n" + "\n".join(lines) + "\n}\n")
    return "\n".join(out)


def extern_decl(m, f):
    args = []
    for p in f.params:
        t = p.type
        n = name_of(p.name)
        const = p.const
        if p.pointer == 2:
            args.append(f"{n}: *mut *mut RawKdTree")
        elif p.dim or p.pointer == 1:
            kind = "*const" if const else "*mut"
            if t == "char":
                args.append(f"{n}: *const c_char")
            elif t == "RantKdTree":
                args.append(f"{n}: {kind} RawKdTree")
            elif t in ("RantShape", "RantShape2D"):
                args.append(f"{n}: {kind} Raw{short(t)}")
            else:
                args.append(f"{n}: {kind} {raw_type(m, t)}")
        else:
            args.append(f"{n}: {raw_type(m, t)}")
    ret = f.ret
    if ret == "void":
        r = ""
    elif ret == "RantMathResult":
        r = " -> c_int"
    elif "*" in ret:
        r = " -> *const c_char" if "char" in ret else " -> *const RawPointFieldView"
    elif ret in ("RantShape", "RantShape2D"):
        r = f" -> Raw{short(ret)}"
    else:
        r = " -> " + raw_type(m, ret)
    return f"    pub fn {f.c}({', '.join(args)}){r};"


def ffi(m):
    decls = [extern_decl(m, f) for f in m.functions if f.c != "rant_math_result_text"]
    return GEN + """use std::ffi::{c_char, c_int};

use rant_types::*;

use super::own::*;

/* A union's bytes. It is only made by a shape_from_ call and read by the library. */
#[repr(C)]
#[derive(Clone, Copy)]
pub struct RawShape {
    words: [u64; 11],
}

#[repr(C)]
#[derive(Clone, Copy)]
pub struct RawShape2D {
    words: [u64; 6],
}

pub enum RawKdTree {}

""" + raw_structs(m) + """
unsafe extern "C" {
    pub fn rant_math_result_text(r: c_int) -> *const c_char;
""" + "\n".join(decls) + """
}
"""


def own_types(m):
    out = [GEN]
    for e in m.own_enums():
        names = e.option_names()
        lines = []
        for i, (n, (_, v)) in enumerate(zip(names, e.options)):
            if i == 0:
                lines.append("    #[default]")
            lines.append(f"    {n} = {v},")
        out.append(f"#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]\n#[repr(i32)]\npub enum {e.short} {{\n" + "\n".join(lines) + "\n}\n")
    for s in m.own_structs():
        lines = [f"    pub {f.name}: {rs_type(m, f.type)}," for f in s.fields]
        out.append(f"#[derive(Clone, Copy, Debug, Default, PartialEq)]\n#[repr(C)]\npub struct {s.short} {{\n" + "\n".join(lines) + "\n}\n")
    return "use rant_types::*;\n\n".join(["", ""]).lstrip() + "\n".join(out)


def enum_readers(m):
    out = []
    for t, name in (("RantImageFormat", "image_format_of"), ("RantScalarKind", "scalar_kind_of")):
        e = m.enums[t]
        arms = "\n".join(f"        {v} => {e.short}::{n}," for n, (_, v) in zip(e.option_names(), e.options))
        default = e.option_names()[0]
        out.append(f"pub(crate) fn {name}(v: i32) -> {e.short} {{\n    match v {{\n{arms}\n        _ => {e.short}::{default},\n    }}\n}}\n")
    return "\n".join(out)


def input_decl(m, f, i):
    n = name_of(i.name)
    k = i.kind
    if k == "value":
        return f"{n}: {rs_type(m, i.type)}"
    if k == "ref":
        return f"{n}: &{rs_type(m, i.type)}"
    if k == "opt_ref":
        return f"{n}: Option<&{rs_type(m, i.type)}>"
    if k == "list":
        return f"{n}: &[{rs_type(m, i.type)}]"
    if k == "image":
        return f"{n}: impl Into<ImageRef<'a>>"
    if k == "image_mut":
        return f"{n}: impl Into<ImageMut<'a>>"
    return f"{n}: " + {
        "string": "&str", "prism": "&Prism", "shape": "&Shape", "shape2d": "&Shape2D", "cloud": "&PointCloud", "cloud_mut": "&mut PointCloud",
        "grid": "&Grid", "grid_mut": "&mut Grid", "scan": "&LaserScan", "det2d": "&[Detection2D]", "det3d": "&[Detection3D]",
        "matrix": "&Matrix", "tree": "&KdTree", "fit_options": "Option<&mut FitOptions<'_>>", "align_options": "Option<&mut AlignOptions<'_>>",
    }[k]


def output_type(m, o):
    k = o.kind
    if k in ("return", "out"):
        return rs_type(m, o.type)
    if k == "fixed":
        return f"[{rs_type(m, o.type)}; {o.size}]"
    if k in ("query", "sized", "same", "expr", "room"):
        return f"Vec<{rs_type(m, o.type)}>"
    return {"matrix": "Matrix", "image": "Image", "image_copy": "Image", "cloud_layout": "PointCloud", "cloud_select": "PointCloud",
            "field": "Option<PointField>", "prism": "Prism", "handle": "KdTree", "shape_new": short(o.type)}[k]


def result_type(m, f):
    outs = [o for o in f.outputs if o.kind != "mutated"]
    if not outs:
        t = "bool" if f.errors == "bool" else "()"
    elif len(outs) == 1:
        t = output_type(m, outs[0])
    else:
        t = "(" + ", ".join(output_type(m, o) for o in outs) + ")"
    if f.errors == "throw":
        return f"Result<{t}, MathError>"
    if f.errors == "optional":
        return f"Option<{t}>"
    return t


class Writer:
    def __init__(self, m, f):
        self.m, self.f = m, f
        self.lines = []
        self.names = {id(i): name_of(i.name) for i in f.inputs}
        self.fails = f.errors == "throw"

    def emit(self, line):
        self.lines.append("    " + line)

    def plain(self, n):
        return n[2:] if n.startswith("r#") else n

    def declare_inputs(self):
        for i in self.f.inputs:
            n = self.names[id(i)]
            c = "c_" + self.plain(n)
            k = i.kind
            if k == "image":
                self.emit(f"let {n}: ImageRef<'a> = {n}.into();")
                self.emit(f"let {c} = {n}.raw();")
            elif k == "image_mut":
                self.emit(f"let mut {n}: ImageMut<'a> = {n}.into();")
                self.emit(f"let mut {c} = {n}.raw();")
            elif k == "cloud":
                self.emit(f"let {c} = CloudRaw::new({n});")
            elif k == "cloud_mut":
                self.emit(f"let mut {c} = CloudRaw::new_mut({n});")
            elif k == "grid":
                self.emit(f"let {c} = GridRaw::new({n});")
            elif k == "grid_mut":
                self.emit(f"let mut {c} = GridRaw::new_mut({n});")
            elif k == "scan":
                self.emit(f"let {c} = scan_raw({n});")
            elif k == "prism":
                self.emit(f"let {c} = prism_raw({n});")
            elif k == "matrix":
                self.emit(f"let {c} = matrix_raw({n})?;")
            elif k == "string":
                self.emit(f"let {c} = cstring({n});")
            elif k == "det2d":
                self.emit(f"let {c}: Vec<ffi::RawDetection2DView> = {n}.iter().map(detection2d_raw).collect();")
            elif k == "det3d":
                self.emit(f"let {c}: Vec<ffi::RawDetection3DView> = {n}.iter().map(detection3d_raw).collect();")
            elif k == "fit_options":
                first = self.names[id(self.f.inputs[0])]
                self.emit(f"let mut {c} = fit_raw({n}, {first}.len())?;")
            elif k == "align_options":
                self.emit(f"let mut {c} = align_raw({n}, source.len(), target.len())?;")
        if self.f.c == "rant_polynomial_at":
            self.emit('assert!(!coefficients.is_empty(), "a polynomial needs a coefficient");')

    def size_words(self, w):
        if w == "min":
            return "a.rows.min(a.cols)"
        if w == "degree + 1":
            return "degree + 1"
        return w

    def image_word(self, w):
        return {
            "src.format": "src.format", "src.width": "src.width", "src.height": "src.height",
            "turned_width": "if quarter_turns.rem_euclid(4) & 1 == 1 { src.height } else { src.width }",
            "turned_height": "if quarter_turns.rem_euclid(4) & 1 == 1 { src.width } else { src.height }",
            "ideal_width": "ideal.unwrap_or(camera).width",
            "ideal_height": "ideal.unwrap_or(camera).height",
        }.get(w, w)

    def declare_outputs(self):
        m = self.m
        for j, o in enumerate(self.f.outputs):
            k = o.kind
            name = f"o{j}"
            t = rs_type(m, o.type) if o.type else ""
            if k == "out":
                self.emit(f"let mut {name} = {t}::default();" if o.type not in RUST_SCALARS else f"let mut {name}: {t} = Default::default();")
            elif k == "fixed":
                self.emit(f"let mut {name} = [{t}::default(); {o.size}];" if o.type not in RUST_SCALARS else f"let mut {name} = [0.0 as {t}; {o.size}];")
            elif k == "same":
                self.emit(f"let mut {name} = vec![{t}::default(); {self.names[id(o.size)]}.len()];")
            elif k in ("sized", "room"):
                self.emit(f"let mut {name} = vec![{t}::default(); {self.names[id(o.size)]} as usize];")
            elif k == "expr":
                self.emit(f"let mut {name} = vec![{t}::default(); ({self.size_words(o.size)}) as usize];")
            elif k == "matrix":
                self.emit(f"let mut {name} = Matrix::new({self.size_words(o.rows)}, {self.size_words(o.cols)});")
            elif k == "image":
                self.emit(f"let mut {name} = new_image({self.image_word(o.size)}, {self.image_word(o.cols)}, {self.image_word(o.rows)});")
                self.emit(f"let mut c{j} = ImageMut::from(&mut {name}).raw();")
            elif k == "image_copy":
                self.emit(f"let mut {name} = c_{self.plain(self.names[id(self.f.inputs[0])])};")
            elif k == "handle":
                self.emit("let mut tree: *mut ffi::RawKdTree = std::ptr::null_mut();")

    def count_of(self, n):
        return f"len32({n}.len())"

    def c_arg(self, a, asking):
        k = a.kind
        m = self.m
        n = self.names.get(id(a.a), "")
        c = "c_" + self.plain(n) if n else ""
        if k == "value":
            if a.a.type in m.enums:
                return f"{n} as i32"
            return n
        if k == "ref":
            return f"{n}"
        if k == "opt_ref":
            return f"{n}.map_or(std::ptr::null(), |x| x as *const _)"
        if k == "list_ptr":
            return f"{n}.as_ptr()"
        if k == "list_count":
            if a.b:
                return f"same({n}.len(), {self.names[id(a.b)]}.len())?"
            return self.count_of(n)
        if k == "degree":
            return f"len32({n}.len() - 1)"
        if k == "view":
            word = m.structs[a.b].fields[0].name
            return f"ffi::Raw{short(a.b)} {{ {word}: {n}.as_ptr(), count: len32({n}.len()) }}"
        if k == "mesh":
            return f"mesh_raw({n}, {self.names[id(a.b)]})"
        if k == "prism":
            return c
        if k == "shape" or k == "shape2d":
            return f"&{n}.raw"
        if k == "image":
            return f"&{c}"
        if k == "image_mut":
            return f"&mut {c}"
        if k == "cloud":
            return f"&{c}.raw"
        if k == "cloud_mut":
            return f"&mut {c}.raw"
        if k == "grid":
            return f"&{c}.raw"
        if k == "grid_mut":
            return f"&mut {c}.raw"
        if k == "scan":
            return f"&{c}"
        if k == "matrix":
            return c
        if k == "string":
            return f"{c}.as_ptr()"
        if k in ("fit_options", "align_options"):
            return f"{c}.as_ptr()"
        if k == "det_ptr":
            return f"{c}.as_ptr()"
        if k == "det_count":
            return f"len32({c}.len())"
        if k == "tree":
            return f"{n}.raw"
        if k == "out":
            o = a.a
            j = self.f.outputs.index(o)
            if o.kind == "handle":
                return "&mut tree"
            if o.kind == "out" or o.kind == "image_copy":
                return f"&mut o{j}"
            if o.kind == "query" and asking:
                return "std::ptr::null_mut()"
            return f"o{j}.as_mut_ptr()"
        if k == "count_ptr":
            o = a.a
            return "&mut n0" if o.kind == "room" else f"&mut n{self.f.outputs.index(o)}"
        if k == "matrix_out":
            j = self.f.outputs.index(a.a)
            return f"o{j}.raw_mut()"
        if k == "image_out":
            return f"&mut c{self.f.outputs.index(a.a)}"
        raise KeyError(k)

    def call(self, asking=False):
        args = ", ".join(self.c_arg(a, asking) for a in self.f.args)
        return f"ffi::{self.f.c}({args})"

    def answer_of(self, o, j):
        m = self.m
        k = o.kind
        if k == "return":
            if o.type in m.enums:
                raise KeyError(o.type)
            return "r"
        if k in ("out", "fixed", "same", "sized", "expr", "room", "query", "matrix", "image"):
            return f"o{j}"
        if k == "image_copy":
            return f"copy_image(&o{j})?"
        if k == "handle":
            return "KdTree { raw: tree }"
        if k == "prism":
            return "prism_of(&r)"
        if k == "cloud_layout":
            return "cloud_like(&r)"
        raise KeyError(k)

    def body(self):
        f = self.f
        if f.c.startswith("rant_shape_from_") or f.c.startswith("rant_shape2d_from_"):
            return self.shape_body()
        if f.c == "rant_point_cloud_field":
            self.emit("let c_cloud = CloudRaw::new(cloud);")
            self.emit("let c_name = cstring(name);")
            self.emit("let found = unsafe { ffi::rant_point_cloud_field(&c_cloud.raw, c_name.as_ptr()) };")
            self.emit("if found.is_null() { None } else { Some(field_of(unsafe { &*found })) }")
            return
        if f.c == "rant_point_cloud_select":
            self.emit("let c_cloud = CloudRaw::new(cloud);")
            self.emit("check(unsafe { ffi::rant_point_cloud_check(&c_cloud.raw) })?;")
            self.emit("if keep.len() != c_cloud.raw.size / c_cloud.raw.point_step as usize { return Err(MathError::Argument); }")
            self.emit("let mut n = 0u32;")
            self.emit("room(unsafe { ffi::rant_point_cloud_select(&c_cloud.raw, keep.as_ptr(), std::ptr::null_mut(), &mut n) })?;")
            self.emit("let mut out = cloud_like(&c_cloud.raw);")
            self.emit("out.data = vec![0u8; n as usize * c_cloud.raw.point_step as usize];")
            self.emit("check(unsafe { ffi::rant_point_cloud_select(&c_cloud.raw, keep.as_ptr(), out.data.as_mut_ptr(), &mut n) })?;")
            self.emit("Ok(out)")
            return
        self.declare_inputs()
        self.declare_outputs()
        asked = [o for o in f.outputs if o.kind == "query" and not hasattr(o.size, "kind")]
        rooms = [o for o in f.outputs if o.kind == "room"]
        if asked:
            for o in asked:
                self.emit(f"let mut n{f.outputs.index(o)} = 0u32;")
            nulls = []
            for j, o in enumerate(f.outputs):
                if o.kind == "query":
                    nulls.append(j)
            # o0 and o1 are not declared yet when asking, so the question passes null pointers.
            self.emit(f"room(unsafe {{ {self.call(True)} }})?;")
            for j, o in enumerate(f.outputs):
                if o.kind == "query":
                    who = f.outputs.index(o.size) if hasattr(o.size, "kind") else j
                    per = f" * {o.per}" if o.per != 1 else ""
                    self.emit(f"let mut o{j} = vec![{rs_type(self.m, o.type)}::default(); n{who} as usize{per}];")
        if rooms:
            self.emit(f"let mut n0 = {self.names[id(rooms[0].size)]};")
        call = self.call()
        outs = [o for o in f.outputs if o.kind != "mutated"]
        answers = [self.answer_of(o, f.outputs.index(o)) for o in outs]
        answer = answers[0] if len(answers) == 1 else ("(" + ", ".join(answers) + ")" if answers else "()")
        if f.ret == "RantMathResult":
            self.emit(f"check(unsafe {{ {call} }})?;")
        elif f.ret == "int":
            if f.outputs:
                self.emit(f"if unsafe {{ {call} }} == 0 {{ return None; }}")
            else:
                self.emit(f"(unsafe {{ {call} }}) != 0")
                return
        elif f.ret == "void":
            self.emit(f"unsafe {{ {call} }};")
        else:
            self.emit(f"let r = unsafe {{ {call} }};")
        for j, o in enumerate(f.outputs):
            if o.kind == "query":
                who = f.outputs.index(o.size) if hasattr(o.size, "kind") else j
                per = f" * {o.per}" if o.per != 1 else ""
                self.emit(f"o{j}.truncate(n{who} as usize{per});")
            elif o.kind == "room":
                self.emit(f"o{j}.truncate(n0 as usize);")
        if f.errors == "throw":
            self.emit(f"Ok({answer})")
        elif f.errors == "optional":
            self.emit(f"Some({answer})")
        elif outs:
            self.emit(answer)

    def shape_body(self):
        f = self.f
        word = f.c.split("_from_")[1]
        i = f.inputs[0]
        n = self.names[id(i)]
        two = f.ret == "RantShape2D"
        cls = "Shape2D" if two else "Shape"
        if word in ("polyline", "polygon", "polyline2d", "polygon2d"):
            view = {"polyline": "RawPolylineView", "polygon": "RawPolygonView", "polyline2d": "RawPolyline2DView", "polygon2d": "RawPolygon2DView"}[word]
            self.emit(f"{cls} {{ raw: unsafe {{ ffi::{f.c}(ffi::{view} {{ points: {n}.as_ptr(), count: len32({n}.len()) }}) }}, data: PhantomData }}")
        elif word == "mesh":
            self.emit("Shape { raw: unsafe { ffi::rant_shape_from_mesh(mesh_raw(vertices, triangles)) }, data: PhantomData }")
        elif word == "prism":
            self.emit("Shape { raw: unsafe { ffi::rant_shape_from_prism(prism_raw(prism)) }, data: PhantomData }")
        else:
            self.emit(f"{cls} {{ raw: unsafe {{ ffi::{f.c}({n}) }}, data: PhantomData }}")


def function(m, f):
    w = Writer(m, f)
    w.body()
    generic = ""
    args = [input_decl(m, f, i) for i in f.inputs]
    if any(i.kind in ("image", "image_mut") for i in f.inputs):
        generic = "<'a>"
    result = result_type(m, f)
    if f.c.startswith("rant_shape_from_") or f.c.startswith("rant_shape2d_from_"):
        generic = "<'a>"
        cls = "Shape" if f.ret == "RantShape" else "Shape2D"
        result = f"{cls}<'a>"
        kind = f.inputs[0].kind
        if kind == "list":
            args = [f"{name_of(i.name)}: &'a [{rs_type(m, i.type)}]" for i in f.inputs]
        elif kind == "prism":
            args = ["prism: &'a Prism"]
    doc = ""
    if f.doc:
        wrapped = textwrap.wrap(f.doc, 100)
        doc = "".join(f"/// {line}\n" for line in wrapped)
    ret = "" if result == "()" else f" -> {result}"
    return f"{doc}pub fn {f.name}{generic}({', '.join(args)}){ret} {{\n" + "\n".join(w.lines) + "\n}\n"


def api(m):
    parts = [GEN, "use std::marker::PhantomData;", "", "use rant_types::*;", "", "use super::own::*;", "use super::*;", "", enum_readers(m)]
    for f in m.functions:
        if f.hand:
            continue
        parts.append(function(m, f))
    return "\n".join(parts)


# The vector test, a thunk per function, and each struct's JSON.

def json_impls(m):
    out = []
    for s in m.used_structs():
        t = s.short
        reads, writes = [], []
        for f in s.fields:
            n = name_of(f.name)
            reads.append(f'{n}: Json::get(&v["{f.name}"])')
            writes.append(f'm.insert("{f.name}".into(), self.{n}.put());')
        out.append(f"impl Json for {t} {{\n    fn get(v: &Value) -> Self {{ {t} {{ {', '.join(reads)} }} }}\n    fn put(&self) -> Value {{\n        let mut m = Map::new();\n        "
                   + "\n        ".join(writes) + "\n        Value::Object(m)\n    }\n}\n")
    for e in m.used_enums():
        arms = ", ".join(f"{v} => {e.short}::{n}" for n, (_, v) in zip(e.option_names(), e.options))
        out.append(f"impl Json for {e.short} {{\n    fn get(v: &Value) -> Self {{ match v.as_i64().unwrap() {{ {arms}, x => panic!(\"no {e.short} {{x}}\") }} }}\n    fn put(&self) -> Value {{ Value::from(*self as i64) }}\n}}\n")
    e = m.enums["RantDistortionModel"]
    arms = ", ".join(f"{v} => {e.short}::{n}" for n, (_, v) in zip(e.option_names(), e.options))
    out.append(f"impl Json for {e.short} {{\n    fn get(v: &Value) -> Self {{ match v.as_i64().unwrap() {{ {arms}, x => panic!(\"no model {{x}}\") }} }}\n    fn put(&self) -> Value {{ Value::from(*self as i64) }}\n}}\n")
    return "\n".join(out)


def thunk(m, f):
    lines = []
    args = []
    for n, i in enumerate(f.inputs):
        k = i.kind
        a = f"&a[{n}]"
        x = f"x{n}"
        if k == "value":
            lines.append(f"let {x}: {rs_type(m, i.type)} = Json::get({a});")
            args.append(x)
        elif k == "ref":
            lines.append(f"let {x}: {rs_type(m, i.type)} = Json::get({a});")
            args.append("&" + x)
        elif k == "opt_ref":
            lines.append(f"let {x}: Option<{rs_type(m, i.type)}> = Json::get({a});")
            args.append(f"{x}.as_ref()")
        elif k == "list":
            lines.append(f"let {x}: Vec<{rs_type(m, i.type)}> = Json::get({a});")
            args.append("&" + x)
        elif k == "string":
            lines.append(f"let {x} = {a}.as_str().unwrap().to_string();")
            args.append("&" + x)
        elif k == "prism":
            lines.append(f"let {x} = get_prism({a});")
            args.append("&" + x)
        elif k == "shape":
            lines.append(f"let h{n} = ShapeData::new({a});")
            lines.append(f"let {x} = h{n}.shape();")
            args.append("&" + x)
        elif k == "shape2d":
            lines.append(f"let h{n} = Shape2DData::new({a});")
            lines.append(f"let {x} = h{n}.shape();")
            args.append("&" + x)
        elif k == "image":
            lines.append(f"let {x} = get_image({a});")
            args.append("&" + x)
        elif k == "image_mut":
            lines.append(f"let mut {x} = get_image({a});")
            args.append("&mut " + x)
        elif k == "cloud":
            lines.append(f"let {x} = get_cloud({a});")
            args.append("&" + x)
        elif k == "cloud_mut":
            lines.append(f"let mut {x} = get_cloud({a});")
            args.append("&mut " + x)
        elif k == "grid":
            lines.append(f"let {x} = get_grid({a});")
            args.append("&" + x)
        elif k == "grid_mut":
            lines.append(f"let mut {x} = get_grid({a});")
            args.append("&mut " + x)
        elif k == "scan":
            lines.append(f"let {x} = get_scan({a});")
            args.append("&" + x)
        elif k == "det2d":
            lines.append(f"let {x} = get_det2d({a});")
            args.append("&" + x)
        elif k == "det3d":
            lines.append(f"let {x} = get_det3d({a});")
            args.append("&" + x)
        elif k == "matrix":
            lines.append(f"let {x} = get_matrix({a});")
            args.append("&" + x)
        elif k == "fit_options":
            lines.append(f"let mut h{n} = FitData::new({a}, a[0].as_array().unwrap().len());")
            lines.append(f"let mut {x} = h{n}.options();")
            args.append(f"{x}.as_mut()")
        elif k == "align_options":
            lines.append(f"let mut h{n} = AlignData::new({a}, a[0].as_array().unwrap().len());")
            lines.append(f"let mut {x} = h{n}.options();")
            args.append(f"{x}.as_mut()")
        elif k == "tree":
            lines.append(f"let {x} = kdtree_create(&<Vec<Double3>>::get(&{a}[\"points\"])).unwrap();")
            args.append("&" + x)
        else:
            raise KeyError(k)
    call = f"rant_math::{f.name}({', '.join(args)})"
    mutated = [o for o in f.outputs if o.kind == "mutated"]
    outs = [o for o in f.outputs if o.kind != "mutated"]
    if f.errors == "throw":
        call += "?"
    if mutated:
        lines.append(f"{call};")
        idx = f.inputs.index(mutated[0].size)
        lines.append(f"let mut out = x{idx}.put();")
    elif not outs and f.errors != "bool":
        lines.append(f"{call};")
        lines.append("let mut out = Value::Null;")
    else:
        lines.append(f"let mut out = {call}.put();")
    extras = []
    for n, i in enumerate(f.inputs):
        if i.kind in ("fit_options", "align_options"):
            extras.append(f"drop(x{n}); h{n}.extras(&mut extra);")
    return lines, extras


def thunks(m):
    rows = [GEN, json_impls(m), "pub fn call(name: &str, a: &[Value], extra: &mut Map<std::string::String, Value>) -> Result<Value, MathError> {",
            "    let _ = &extra;", "    match name {"]
    for f in m.functions:
        if not f.vector:
            continue
        lines, extras = thunk(m, f)
        extras_text = " ".join(e.replace("&mut extra", "extra") for e in extras)
        body = " ".join(lines)
        rows.append(f'        "{f.name}" => {{ {body} {extras_text} let _ = &mut out; Ok(out) }}')
    rows += ['        other => panic!("no thunk for {other}"),', "    }", "}", ""]
    return "\n".join(rows)



def result_hint(f):
    outs = [o for o in f.outputs if o.kind != "mutated"]
    if not outs:
        return "bool" if f.errors == "bool" else "None"
    t = output_hint(outs[0]) if len(outs) == 1 else "Tuple[" + ", ".join(output_hint(o) for o in outs) + "]"
    return f"Optional[{t}]" if f.errors == "optional" else t


def input_decl(i):
    n = f"{arg_name(i.name)}: {input_hint(i)}"
    if i.kind in ("fit_options", "align_options", "opt_ref"):
        return f"{n} = None"
    return n


def function(m, f):
    w = Writer(m, f)
    w.body()
    # An argument after one with a default takes one too.
    args = []
    seen_default = False
    for i in f.inputs:
        d = input_decl(i)
        if "=" in d:
            seen_default = True
        elif seen_default:
            d += " = None"
        args.append(d)
    doc = ""
    if f.doc:
        wrapped = textwrap.wrap(f.doc, 100)
        doc = '    """' + "\n    ".join(wrapped) + '"""\n'
    return f"def {f.name}({', '.join(args)}) -> {result_hint(f)}:\n" + doc + "\n".join(w.lines) + "\n"



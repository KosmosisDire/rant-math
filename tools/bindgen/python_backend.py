def _is_numpy(v):
    return type(v).__module__.split(".")[0] == "numpy"


def _list_in(values, ctype, to_c, np_kind, per, copy=False):
    """A C pointer and count for a list: a numpy array goes as it is, anything else copied in."""
    if _is_numpy(values) and np_kind is not None:
        import numpy
        array = numpy.array(values, dtype=np_kind, order="C", copy=True if copy else None)
        if array.size == 0:
            return None, 0, True
        if per == 1:
            array = array.reshape(-1)
        elif array.ndim == 1 and array.size == per:
            array = array.reshape(1, per)
        elif array.ndim != 2 or array.shape[1] != per:
            raise MathError(ErrorKind.Argument)

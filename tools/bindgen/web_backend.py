def result_type(m, w, f):
    outs = [o for o in f.outputs if o.kind != "mutated"]
    if not outs:
        return "boolean" if f.errors == "bool" else "void"
    t = output_type(m, w, outs[0]) if len(outs) == 1 else "[" + ", ".join(output_type(m, w, o) for o in outs) + "]"
    if f.errors == "optional":
        return f"{t} | null"
    return t


def function(m, lay, f):
    w = Writer(m, lay, f)
    w.generate()
    decls = [input_decl(m, w, i) for i in f.inputs]
    doc = ""
    if f.doc:
        wrapped = textwrap.wrap(f.doc.replace("*/", ""), 100)
        doc = "/** " + "\n * ".join(wrapped) + " */\n"
    return f"{doc}export function {camel(f.name)}({', '.join(decls)}): {result_type(m, w, f)} {{\n" + "\n".join(w.lines) + "\n}\n"



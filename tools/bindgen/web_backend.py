from python_backend import C_TYPES  # noqa: F401

GEN = "/* Generated by tools/bindgen/gen.py from src/, do not edit. */\n"

SIZES = {"double": 8, "float": 4, "int": 4, "int8_t": 1, "uint8_t": 1, "int16_t": 2, "uint16_t": 2, "int32_t": 4, "uint32_t": 4,
         "int64_t": 8, "uint64_t": 8, "size_t": 4, "char": 1}
TS_NUMBER = set(SIZES) - {"char"}
HEAP = {"double": ("F64", 3), "float": ("F32", 2), "int": ("I32", 2), "int8_t": ("I8", 0), "uint8_t": ("U8", 0), "int16_t": ("I16", 1),
        "uint16_t": ("U16", 1), "int32_t": ("I32", 2), "uint32_t": ("U32", 2), "size_t": ("U32", 2)}
ALIASES = {"RantMatrix3x3": "Float32Array", "RantMatrix4x4": "Float32Array", "RantCovariance3": "Float64Array", "RantCovariance6": "Float64Array"}
TYPED = {"double": "Float64Array", "float": "Float32Array", "uint32_t": "Uint32Array", "uint8_t": "Uint8Array"}

# Structs written with pointers in them, whose fields the hand written part fills.
RAW_STRUCTS = ["RantPolygonView", "RantPolygon2DView", "RantPolylineView", "RantPolyline2DView", "RantPathView", "RantPath2DView",
               "RantPrismView", "RantMeshView", "RantMatrixView", "RantImageView", "RantPointFieldView", "RantPointCloudView",
               "RantGridFieldView", "RantGridView", "RantLaserScanView", "RantDetection2DView", "RantDetection3DView",
               "RantFitOptions", "RantAlignOptions"]


def short(t):
    return t[4:] if t.startswith("Rant") else t


def camel(name):
    parts = name.split("_")
    return parts[0] + "".join(p[0].upper() + p[1:] for p in parts[1:] if p)


class Layout:
    """The wasm32 layout of a struct, the same rule a C compiler follows there."""

    def __init__(self, m):
        self.m = m
        self.cache = {}

    def of(self, t):
        if t in SIZES:
            return SIZES[t], SIZES[t], []
        if t in self.m.enums:
            return 4, 4, []
        if t in self.cache:
            return self.cache[t]
        s = self.m.structs[t]
        offset, align, fields = 0, 1, []
        for f in s.fields:
            if f.pointer:
                size, al = 4, 4
            else:
                size, al, _ = self.of(f.type)
                for d in f.dims:
                    size *= d
            offset = (offset + al - 1) // al * al
            fields.append((f, offset))
            offset += size
            align = max(align, al)
        size = (offset + align - 1) // align * align
        self.cache[t] = (size, align, fields)
        return self.cache[t]

    def size(self, t):
        return self.of(t)[0]


def write_field(m, lay, f, base, expr, out, indent):
    """Lines that write one value of field f to the heap at byte offset expression base."""
    t = f.type
    if f.pointer:
        out.append(f"{indent}U32[({base}) >> 2] = {expr};")
        return
    write_value(m, lay, t, f.dims, base, expr, out, indent)


def write_value(m, lay, t, dims, base, expr, out, indent):
    if dims:
        size = lay.size(t)
        for d in dims[1:]:
            size *= d
        i = "i" + str(len(dims))
        out.append(f"{indent}for (let {i} = 0; {i} < {dims[0]}; {i}++) {{")
        write_value(m, lay, t, dims[1:], f"{base} + {i} * {size}", f"{expr}[{i}]", out, indent + "    ")
        out.append(f"{indent}}}")
    elif t in ("uint64_t", "int64_t"):
        out.append(f"{indent}F64[({base}) >> 3] = 0;")
        out.append(f"{indent}U32[({base}) >> 2] = {expr} >>> 0;")
        out.append(f"{indent}U32[(({base}) + 4) >> 2] = Math.floor({expr} / 4294967296);")
    elif t in m.enums:
        out.append(f"{indent}I32[({base}) >> 2] = {enum_in(m, t, expr)};")
    elif t in HEAP:
        heap, shift = HEAP[t]
        out.append(f"{indent}{heap}[({base}) >> {shift}] = {expr};")
    else:
        out.append(f"{indent}w_{t}({base}, {expr});")


def enum_in(m, t, expr):
    # A value may come by its name, as the standard types spell it, or by its number.
    return f"enumIn({short(t)}Values, {expr})"


def read_value(m, lay, t, dims, base):
    if dims:
        size = lay.size(t)
        for d in dims[1:]:
            size *= d
        i = "i" + str(len(dims))
        inner = read_value(m, lay, t, dims[1:], f"{base} + {i} * {size}")
        return f"Array.from({{ length: {dims[0]} }}, (_, {i}) => {inner})"
    if t in ("uint64_t", "int64_t"):
        return f"(U32[({base}) >> 2] + U32[(({base}) + 4) >> 2] * 4294967296)"
    if t in m.enums:
        return f"{short(t)}Names[I32[({base}) >> 2]]"
    if t in HEAP:
        heap, shift = HEAP[t]
        return f"{heap}[({base}) >> {shift}]"
    return f"r_{t}({base})"


def structs_ts(m, lay):
    out = []
    order = [s.name for s in m.used_structs()]
    for t in order:
        s = m.structs[t]
        size, _, fields = lay.of(t)
        body = []
        for f, off in fields:
            if t == "RantCameraIntrinsics" and f.name == "model":
                body.append(f"    const model = enumIn(DistortionModelValues, v.model);")
                body.append(f"    F64[(p + {off}) >> 3] = 0;")
                body.append(f"    U32[(p + {off}) >> 2] = model;")
                continue
            if t == "RantCameraIntrinsics" and f.name == "coeffs":
                body.append(f"    for (let i = 0; i < 8; i++) F64[(p + {off} + i * 8) >> 3] = v.coeffs?.[i] ?? 0;")
                continue
            expr = f"v.{f.name}"
            if t in ALIASES:
                expr = "v"
            write_field(m, lay, f, f"p + {off}", expr, body, "    ")
        vt = "any" if t in ALIASES else short(t)
        out.append(f"function w_{t}(p: number, v: {vt}): void {{\n" + "\n".join(body) + "\n}\n")
        if t in ALIASES:
            f, off = fields[0]
            dims = f.dims
            arr = ALIASES[t]
            per = lay.size(f.type)
            n = dims[0]
            heap = "F32" if arr == "Float32Array" else "F64"
            out.append(f"function r_{t}(p: number): {arr}[] {{\n    return Array.from({{ length: {n} }}, (_, i) => {heap}.slice((p >> {2 if arr == 'Float32Array' else 3}) + i * {n}, (p >> {2 if arr == 'Float32Array' else 3}) + (i + 1) * {n}));\n}}\n")
            continue
        if t == "RantCameraIntrinsics":
            reads = []
            for f, off in fields:
                if f.name == "model":
                    reads.append(f"model: DistortionModelNames[U32[(p + {off}) >> 2]] as DistortionModel")
                elif f.name == "coeffs":
                    reads.append(f"coeffs: F64.slice((p + {off}) >> 3, ((p + {off}) >> 3) + 8)")
                else:
                    reads.append(f"{f.name}: {read_value(m, lay, f.type, f.dims, f'p + {off}')}")
        else:
            reads = [f"{f.name}: {read_value(m, lay, f.type, f.dims, f'p + {off}')}" for f, off in fields]
        ret = "CameraOut" if t == "RantCameraIntrinsics" else short(t)
        out.append(f"function r_{t}(p: number): {ret} {{\n    return {{ {', '.join(reads)} }};\n}}\n")
    for t in RAW_STRUCTS:
        size, _, fields = lay.of(t)
        body = []
        for f, off in fields:
            write_field(m, lay, f, f"p + {off}", f"v.{f.name}", body, "    ")
        reads = []
        for f, off in fields:
            if f.pointer:
                reads.append(f"{f.name}: U32[(p + {off}) >> 2]")
            else:
                reads.append(f"{f.name}: {read_value(m, lay, f.type, f.dims, f'p + {off}')}")
        out.append(f"function w_{t}(p: number, v: any): void {{\n" + "\n".join(body) + "\n}\n")
        out.append(f"function r_{t}(p: number): any {{\n    return {{ {', '.join(reads)} }};\n}}\n")
    return "\n".join(out)


def ts_field_type(m, f, owner):
    t = f.type
    if owner == "RantCameraIntrinsics" and f.name == "model":
        return "DistortionModel"
    if f.dims:
        if owner == "RantCameraIntrinsics":
            return "ArrayLike<number>"
    return ts_value_type(m, t)


def ts_value_type(m, t):
    if t in TS_NUMBER:
        return "number"
    if t in ALIASES:
        return short(t)
    if t in m.enums:
        return short(t)
    return short(t)


def types_ts(m):
    out = []
    for e in m.used_enums() + [m.enums["RantDistortionModel"], m.enums["RantScalarKind"]]:
        names = e.option_names()
        if e.short in [x.split(" ")[2] for x in out if x.startswith("export type ")]:
            continue
        out.append(f"export type {e.short} = " + " | ".join(f'"{n}"' for n in names) + ";")
        out.append(f"const {e.short}Values: Record<string, number> = {{ " + ", ".join(f'{n}: {v}' for n, (_, v) in zip(names, e.options)) + " };")
        out.append(f"const {e.short}Names: Record<number, {e.short}> = {{ " + ", ".join(f'{v}: "{n}"' for n, (_, v) in zip(names, e.options)) + " };")
        out.append("")
    for t, arr in ALIASES.items():
        out.append(f"export type {short(t)} = {arr}[] | ArrayLike<ArrayLike<number>>;")
    out.append("")
    seen = set()
    for s in m.used_structs():
        if s.name in ALIASES or s.name in seen:
            continue
        seen.add(s.name)
        fields = "\n".join(f"    {f.name}: {ts_field_type(m, f, s.name)};" for f in s.fields)
        out.append(f"export interface {s.short} {{\n{fields}\n}}\n")
    return "\n".join(out)


# The shim.

def shim_param(m, p):
    t = p.type
    if p.pointer == 2:
        return f"{t} **{p.name}"
    if p.dim:
        return f"{t} *{p.name}"
    if p.pointer:
        return ("const " if p.const else "") + f"{t} *{p.name}"
    if t in m.structs:
        return f"const {t} *{p.name}"
    if t == "uint64_t":
        return f"double {p.name}"
    return f"{t} {p.name}"


def shim_arg(m, p):
    if p.pointer or p.dim:
        return p.name
    if p.type in m.structs:
        return f"*{p.name}"
    if p.type == "uint64_t":
        return f"(uint64_t){p.name}"
    return p.name


def shim(m, lay):
    out = [GEN, '#include <stddef.h>', '#include <emscripten.h>', '#include "rant_math.h"', ""]
    for t in sorted(set(s.name for s in m.used_structs()) | set(RAW_STRUCTS)):
        size, _, fields = lay.of(t)
        out.append(f"_Static_assert(sizeof({t}) == {size}, \"{t}\");")
        for f, off in fields:
            out.append(f"_Static_assert(offsetof({t}, {f.name}) == {off}, \"{t}.{f.name}\");")
    out.append("")
    names = ["_malloc", "_free", "_rm_result_text"]
    for f in m.functions:
        if f.c == "rant_math_result_text":
            continue
        params = [shim_param(m, p) for p in f.params]
        args = ", ".join(shim_arg(m, p) for p in f.params)
        name = "rm_" + f.name
        names.append("_" + name)
        ret = f.ret
        if ret in m.structs:
            head = ", ".join([f"{ret} *ret"] + params)
            body = f"*ret = {f.c}({args});"
            sig = "void"
        elif ret == "void":
            head = ", ".join(params) or "void"
            body = f"{f.c}({args});"
            sig = "void"
        else:
            head = ", ".join(params) or "void"
            body = f"return {f.c}({args});"
            sig = ret
        out.append(f"EMSCRIPTEN_KEEPALIVE {sig} {name}({head}) {{ {body} }}")
    out.append("EMSCRIPTEN_KEEPALIVE const char *rm_result_text(int r) { return rant_math_result_text((RantMathResult)r); }")
    return "\n".join(out) + "\n", names


class Writer:
    def __init__(self, m, lay, f):
        self.m, self.lay, self.f = m, lay, f
        self.lines = []
        self.names = {id(i): self.param_name(i.name) for i in f.inputs}
        self.typed = []

    def param_name(self, n):
        if n in ("in", "from", "function", "var", "default", "delete", "new", "class"):
            return n + "_"
        return camel(n)

    def emit(self, line):
        self.lines.append("    " + line)

    def declare_inputs(self):
        m, lay = self.m, self.lay
        for i in self.f.inputs:
            n = self.names[id(i)]
            c = "c_" + n.rstrip("_")
            k = i.kind
            if k == "ref" or (k == "value" and i.type in m.structs):
                size = lay.size(i.type)
                self.emit(f"const {c} = alloc({size}); w_{i.type}({c}, {n});")
            elif k == "opt_ref":
                size = lay.size(i.type)
                self.emit(f"const {c} = {n} ? alloc({size}) : 0; if ({n}) w_{i.type}({c}, {n});")
            elif k == "list":
                self.list_input(i, n, c)
            elif k == "prism":
                self.emit(f"const {c} = prismIn({n});")
            elif k == "shape":
                self.emit(f"const {c} = shapeIn({n});")
            elif k == "shape2d":
                self.emit(f"const {c} = shape2dIn({n});")
            elif k in ("image", "image_mut"):
                self.emit(f"const {c} = imageIn({n});")
            elif k in ("cloud", "cloud_mut"):
                self.emit(f"const {c} = cloudIn({n});")
            elif k in ("grid", "grid_mut"):
                self.emit(f"const {c} = gridIn({n});")
            elif k == "scan":
                self.emit(f"const {c} = scanIn({n});")
            elif k == "det2d":
                self.emit(f"const {c} = detectionsIn({n}, {lay.size('RantDetection2DView')}, w_RantDetection2DView, w_RantOrientedBox2D);")
            elif k == "det3d":
                self.emit(f"const {c} = detectionsIn({n}, {lay.size('RantDetection3DView')}, w_RantDetection3DView, w_RantOrientedBox);")
            elif k == "matrix":
                self.emit(f"const {c} = matrixIn({n});")
            elif k == "string":
                self.emit(f"const {c} = stringIn({n});")
            elif k == "fit_options":
                first = self.names[id(self.f.inputs[0])]
                self.emit(f"const {c} = fitIn({n}, n_{first.rstrip('_')});")
            elif k == "align_options":
                self.emit(f"const {c} = alignIn({n}, n_source, n_target);")
        if self.f.c == "rant_polynomial_at":
            self.emit("if (n_coefficients === 0) throw new MathError(-1);")

    def list_input(self, i, n, c):
        t = i.type
        bare = n.rstrip("_")
        if t in TYPED:
            self.emit(f"const n_{bare} = lengthOf({n}); const {c} = numbersIn({n}, {SIZES[t]}, {TYPED[t]});")
            return
        size = self.lay.size(t)
        flat = self.flat_of(t)
        self.emit(f"const n_{bare} = countOf({n}, {flat}); const {c} = listIn({n}, n_{bare}, {size}, w_{t});")
        if flat:
            self.typed.append(f"{n} instanceof Float64Array")

    def flat_of(self, t):
        # How many doubles a struct is when it is doubles alone, so a Float64Array can stand for a list.
        s = self.m.structs.get(t)
        if s is None:
            return 0
        total = 0
        for f in s.fields:
            if f.type == "double" and not f.dims:
                total += 1
            elif f.type in self.m.structs:
                inner = self.flat_of(f.type)
                if not inner:
                    return 0
                total += inner
            else:
                return 0
        return total

    def typed_out(self):
        return " || ".join(self.typed) if self.typed else "false"

    def size_words(self, w):
        if w == "min":
            return "Math.min(a.rows, a.cols)"
        if w == "degree + 1":
            return "degree + 1"
        return w

    def image_word(self, w):
        return {
            "src.format": "src.format", "src.width": "src.width", "src.height": "src.height",
            "turned_width": "(((quarterTurns % 4) + 4) % 4) & 1 ? src.height : src.width",
            "turned_height": "(((quarterTurns % 4) + 4) % 4) & 1 ? src.width : src.height",
            "ideal_width": "(ideal ?? camera).width",
            "ideal_height": "(ideal ?? camera).height",
        }.get(w, camel(w))

    def element_size(self, o):
        return SIZES[o.type] if o.type in SIZES else self.lay.size(o.type)

    def declare_outputs(self):
        for j, o in enumerate(self.f.outputs):
            k = o.kind
            name = f"o{j}"
            if k == "out":
                self.emit(f"const {name} = alloc({self.element_size(o)});")
            elif k == "fixed":
                self.emit(f"const {name} = alloc({self.element_size(o)} * {o.size});")
            elif k == "same":
                bare = self.names[id(o.size)].rstrip("_")
                n = f"{self.names[id(o.size)]}.length" if o.size.kind in ("det2d", "det3d") else f"n_{bare}"
                self.emit(f"const s{j} = {n}; const {name} = alloc({self.element_size(o)} * s{j});")
            elif k in ("sized", "room"):
                self.emit(f"const s{j} = {self.names[id(o.size)]}; const {name} = alloc({self.element_size(o)} * s{j});")
            elif k == "expr":
                self.emit(f"const s{j} = {self.size_words(o.size)}; const {name} = alloc({self.element_size(o)} * s{j});")
            elif k == "matrix":
                self.emit(f"const {name} = matrixOut({self.size_words(o.rows)}, {self.size_words(o.cols)});")
            elif k == "image":
                self.emit(f"const {name} = imageOut({self.image_word(o.size)}, {self.image_word(o.cols)}, {self.image_word(o.rows)});")
            elif k == "image_copy":
                self.emit(f"const {name} = alloc({self.lay.size('RantImageView')});")
            elif k == "handle":
                self.emit("const tree = alloc(4);")

    def c_arg(self, a, asking):
        k = a.kind
        n = self.names.get(id(a.a), "")
        bare = n.rstrip("_")
        c = "c_" + bare
        m = self.m
        if k == "value":
            if a.a.type in m.structs:
                return c
            if a.a.type in m.enums:
                return enum_in(m, a.a.type, n)
            return n
        if k in ("ref", "opt_ref", "shape", "shape2d", "prism", "matrix", "string", "fit_options", "align_options"):
            return c
        if k in ("image", "image_mut", "cloud", "cloud_mut", "grid", "grid_mut", "scan"):
            return c
        if k == "list_ptr" or k == "det_ptr":
            return c
        if k == "list_count":
            if a.b:
                return f"sameCount(n_{bare}, n_{self.names[id(a.b)].rstrip('_')})"
            return f"n_{bare}"
        if k == "det_count":
            return f"{n}.length"
        if k == "degree":
            return f"n_{bare} - 1"
        if k == "view":
            word = m.structs[a.b].fields[0].name
            return f"viewIn({c}, n_{bare})"
        if k == "mesh":
            other = self.names[id(a.b)].rstrip("_")
            return f"meshIn(c_{bare}, n_{bare}, c_{other}, n_{other})"
        if k == "tree":
            return f"{n}.handle()"
        if k == "out":
            o = a.a
            j = self.f.outputs.index(o)
            if o.kind == "handle":
                return "tree"
            if o.kind == "query" and asking:
                return "0"
            return f"o{j}"
        if k == "count_ptr":
            o = a.a
            return "n0" if o.kind == "room" else f"n{self.f.outputs.index(o)}"
        if k == "matrix_out":
            return f"o{self.f.outputs.index(a.a)}.view"
        if k == "image_out":
            return f"o{self.f.outputs.index(a.a)}.view"
        raise KeyError(k)

    def call(self, asking=False):
        args = [self.c_arg(a, asking) for a in self.f.args]
        return f"wasm._rm_{self.f.name}({', '.join(args)})"

    def answer_of(self, o, j):
        k = o.kind
        m = self.m
        if k == "return":
            if o.type in TS_NUMBER:
                return "r"
            return f"r_{o.type}(ret)"
        if k == "out":
            if o.type in TS_NUMBER:
                return read_value(m, self.lay, o.type, (), f"o{j}")
            return f"r_{o.type}(o{j})"
        if k in ("fixed", "same", "sized", "expr", "room", "query"):
            if k == "fixed":
                n = str(o.size)
            elif k == "query":
                who = self.f.outputs.index(o.size) if hasattr(o.size, "kind") else j
                n = f"U32[n{who} >> 2]" + (f" * {o.per}" if o.per != 1 else "")
            elif k == "room":
                n = "U32[n0 >> 2]"
            else:
                n = f"s{j}"
            if o.type in TYPED:
                return f"numbersOut(o{j}, {n}, {TYPED[o.type]})"
            flat = self.flat_of(o.type)
            if flat:
                return f"listOut(o{j}, {n}, {self.lay.size(o.type)}, r_{o.type}, {flat}, {self.typed_out()})"
            return f"listOut(o{j}, {n}, {self.lay.size(o.type)}, r_{o.type}, 0, false)"
        if k == "matrix":
            return f"o{j}.matrix()"
        if k == "image":
            return f"o{j}.image()"
        if k == "image_copy":
            return f"imageCopy(o{j})"
        if k == "handle":
            return "new KdTree(U32[tree >> 2])"
        if k == "prism":
            return "prismOf(ret)"
        if k == "cloud_layout":
            return "cloudLike(ret)"
        raise KeyError(k)

    def generate(self):
        f = self.f
        if f.c.startswith("rant_shape_from_") or f.c.startswith("rant_shape2d_from_"):
            return self.shape_body()
        if f.c == "rant_point_cloud_field":
            self.emit("begin();")
            self.emit("const c_cloud = cloudIn(cloud);")
            self.emit("const found = wasm._rm_point_cloud_field(c_cloud, stringIn(name));")
            self.emit("refresh();")
            self.emit("return found ? fieldOf(found) : null;")
            return
        if f.c == "rant_point_cloud_select":
            self.emit("begin();")
            self.emit("const c_cloud = cloudIn(cloud);")
            self.emit("check(wasm._rm_point_cloud_check(c_cloud));")
            self.emit(f"const view = r_RantPointCloudView(c_cloud);")

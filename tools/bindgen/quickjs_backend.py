# The Rust crate's QuickJS glue, for a program that scripts in QuickJS and so has no wasm: the same
# names and the same plain values as the TypeScript binding, through one host function by number.
import json

from rust_backend import RUST_SCALARS, name_of, rs_type, short
from web_backend import camel

GEN = "// Generated by tools/bindgen/gen.py from src/, do not edit.\n"

ALIASES = {"RantMatrix3x3": "f32", "RantMatrix4x4": "f32", "RantCovariance3": "f64", "RantCovariance6": "f64"}
NUMBERS = {"double", "float", "uint32_t", "uint8_t"}


def flat_of(m, t):
    s = m.structs.get(t)
    if s is None:
        return 0
    total = 0
    for f in s.fields:
        if f.type == "double" and not f.dims:
            total += 1
        elif f.type in m.structs:
            inner = flat_of(m, f.type)
            if not inner:
                return 0
            total += inner
        else:
            return 0
    return total


def enum_impls(m):
    out = []
    enums = list(m.used_enums())
    for t in ("RantDistortionModel", "RantScalarKind"):
        if m.enums[t] not in enums:
            enums.append(m.enums[t])
    for e in enums:
        t = e.short
        names = e.option_names()
        by_name = ", ".join(f'"{n}" => Ok({t}::{n})' for n in names)
        by_number = ", ".join(f"{v} => Ok({t}::{n})" for n, (_, v) in zip(names, e.options))
        to_name = ", ".join(f'{t}::{n} => "{n}"' for n in names)
        out.append(f"""impl<'js> Js<'js> for {t} {{
    fn get(ctx: &Ctx<'js>, v: &Value<'js>) -> JsResult<Self> {{
        if let Some(n) = v.as_number() {{
            return match n as i64 {{ {by_number}, _ => Err(fail_argument(ctx)) }};
        }}
        let text = v.as_string().map(|s| s.to_string()).transpose()?.unwrap_or_default();
        match text.as_str() {{ {by_name}, _ => Err(fail_argument(ctx)) }}
    }}
    fn put(&self, ctx: &Ctx<'js>) -> JsResult<Value<'js>> {{
        let name = match self {{ {to_name} }};
        Ok(rquickjs::String::from_str(ctx.clone(), name)?.into_value())
    }}
}}
""")
    return "\n".join(out)


def struct_impls(m):
    out = []
    for s in m.used_structs():
        t = s.short
        if s.name in ALIASES:
            el = ALIASES[s.name]
            n = s.fields[0].dims[0]
            out.append(f"impl<'js> Js<'js> for {t} {{\n    fn get(ctx: &Ctx<'js>, v: &Value<'js>) -> JsResult<Self> {{ Ok({t} {{ m: rows::<{el}, {n}>(ctx, v)? }}) }}\n"
                       f"    fn put(&self, ctx: &Ctx<'js>) -> JsResult<Value<'js>> {{ rows_out::<{el}, {n}>(ctx, &self.m) }}\n}}\n")
            continue
        reads, writes = [], []
        for f in s.fields:
            n = name_of(f.name)
            if s.name == "RantCameraIntrinsics" and f.name == "coeffs":
                reads.append("coeffs: coeffs(ctx, v)?")
                writes.append('o.set("coeffs", numbers_out(ctx, &self.coeffs)?)?;')
            else:
                reads.append(f'{n}: field(ctx, v, "{f.name}")?')
                writes.append(f'o.set("{f.name}", self.{n}.put(ctx)?)?;')
        out.append(f"impl<'js> Js<'js> for {t} {{\n    fn get(ctx: &Ctx<'js>, v: &Value<'js>) -> JsResult<Self> {{ Ok({t} {{ {', '.join(reads)} }}) }}\n"
                   f"    fn put(&self, ctx: &Ctx<'js>) -> JsResult<Value<'js>> {{\n        let o = Object::new(ctx.clone())?;\n        " + "\n        ".join(writes) + "\n        Ok(o.into_value())\n    }\n}\n")
    return "\n".join(out)


def arm(m, f, index):
    lines = []
    args = []
    typed = []
    for n, i in enumerate(f.inputs):
        k = i.kind
        a = f"&at(args, {n})"
        x = f"x{n}"
        t = rs_type(m, i.type) if i.type else ""
        if k == "value":
            lines.append(f"let {x}: {t} = Js::get(ctx, {a})?;")
            args.append(x)
        elif k == "ref":
            lines.append(f"let {x}: {t} = Js::get(ctx, {a})?;")
            args.append("&" + x)
        elif k == "opt_ref":
            lines.append(f"let {x}: Option<{t}> = maybe(ctx, {a})?;")
            args.append(f"{x}.as_ref()")
        elif k == "list":
            if i.type in NUMBERS:
                lines.append(f"let {x}: Vec<{t}> = numbers(ctx, {a})?;")
            else:
                flat = flat_of(m, i.type)
                lines.append(f"let ({x}, t{n}): (Vec<{t}>, bool) = list(ctx, {a}, {flat}).map_err(|_| math_error(ctx, fail, MathError::Argument))?;")
                typed.append(f"t{n}")
            args.append("&" + x)
        elif k == "string":
            lines.append(f"let {x}: std::string::String = text(ctx, {a})?;")
            args.append("&" + x)
        elif k == "prism":
            lines.append(f"let {x} = prism_in(ctx, {a})?;")
            args.append("&" + x)
        elif k == "shape":
            lines.append(f"let h{n} = ShapeHold::new(ctx, {a})?;")
            lines.append(f"let {x} = h{n}.shape(ctx)?;")
            args.append("&" + x)
        elif k == "shape2d":
            lines.append(f"let h{n} = Shape2DHold::new(ctx, {a})?;")
            lines.append(f"let {x} = h{n}.shape(ctx)?;")
            args.append("&" + x)
        elif k == "image":
            lines.append(f"let {x} = image_in(ctx, {a})?;")
            args.append("&" + x)
        elif k == "image_mut":
            lines.append(f"let mut {x} = image_in(ctx, {a})?;")
            args.append("&mut " + x)
        elif k == "cloud":
            lines.append(f"let {x} = cloud_in(ctx, {a})?;")
            args.append("&" + x)
        elif k == "cloud_mut":
            lines.append(f"let mut {x} = cloud_in(ctx, {a})?;")
            args.append("&mut " + x)
        elif k == "grid":
            lines.append(f"let {x} = grid_in(ctx, {a})?;")
            args.append("&" + x)
        elif k == "grid_mut":
            lines.append(f"let mut {x} = grid_in(ctx, {a})?;")
            args.append("&mut " + x)
        elif k == "scan":
            lines.append(f"let {x} = scan_in(ctx, {a})?;")
            args.append("&" + x)
        elif k == "det2d":
            lines.append(f"let {x} = detections2d_in(ctx, {a})?;")
            args.append("&" + x)
        elif k == "det3d":
            lines.append(f"let {x} = detections3d_in(ctx, {a})?;")
            args.append("&" + x)
        elif k == "matrix":
            lines.append(f"let {x} = matrix_in(ctx, {a})?;")
            args.append("&" + x)
        elif k == "fit_options":
            lines.append(f"let mut h{n} = FitHold::new(ctx, {a})?;")
            lines.append(f"let mut {x} = h{n}.options();")
            args.append(f"{x}.as_mut()")
        elif k == "align_options":
            lines.append(f"let mut h{n} = AlignHold::new(ctx, {a})?;")
            lines.append(f"let mut {x} = h{n}.options();")
            args.append(f"{x}.as_mut()")
        elif k == "tree":
            lines.append(f"let {x} = tree_of(ctx, trees, {a})?;")
            args.append("&*" + x)
        else:
            raise KeyError(k)
    # What the crate panics over, a script hears as an error.
    guards = ""
    for a2 in f.args:
        if a2.kind == "mesh":
            guards += f"if x{f.inputs.index(a2.b)}.len() % 3 != 0 {{ return Err(math_error(ctx, fail, MathError::Argument)); }} "
        elif a2.kind == "degree":
            guards += f"if x{f.inputs.index(a2.a)}.is_empty() {{ return Err(math_error(ctx, fail, MathError::Argument)); }} "
    if guards:
        lines.append(guards.strip())
    call = f"crate::{f.name}({', '.join(args)})"
    outs = [o for o in f.outputs if o.kind != "mutated"]
    mutated = [o for o in f.outputs if o.kind == "mutated"]
    typed_expr = " || ".join(typed) or "false"

    def piece(o, expr):
        if o.kind in ("query", "sized", "same", "expr", "room", "fixed"):
            if o.type in NUMBERS:
                return f"numbers_out(ctx, &{expr})?"
            flat = flat_of(m, o.type)
            return f"list_out(ctx, &{expr}, {typed_expr}, {flat})?"
        return f"{expr}.put(ctx)?"

    if f.errors == "throw":
        call = f"{call}.map_err(|e| math_error(ctx, fail, e))?"
    tail = []
    if f.name == "kdtree_create":
        lines.append(f"let r = {call};")
        tail.append("Ok(Value::new_number(ctx.clone(), trees.borrow_mut().insert(r) as f64))")
    elif mutated:
        lines.append(f"{call};")
        idx = f.inputs.index(mutated[0].size)
        kind = f.inputs[idx].kind
        back = {"image_mut": "image_back", "cloud_mut": "cloud_back", "grid_mut": "grid_back"}[kind]
        lines.append(f"{back}(&at(args, {idx}), &x{idx})?;")
        tail.append("Ok(Value::new_undefined(ctx.clone()))")
    elif not outs and f.errors != "bool":
        lines.append(f"{call};")
        tail.append("Ok(Value::new_undefined(ctx.clone()))")
    elif f.errors == "bool":
        tail.append(f"Ok(Value::new_bool(ctx.clone(), {call}))")
    elif f.errors == "optional":
        expr = "r"
        tail.append(f"match {call} {{ None => Ok(Value::new_null(ctx.clone())), Some(r) => Ok({piece(outs[0], 'r')}) }}")
    elif len(outs) == 1:
        lines.append(f"let r = {call};")
        tail.append(f"Ok({piece(outs[0], 'r')})")
    else:
        names = ", ".join(f"r{i}" for i in range(len(outs)))
        lines.append(f"let ({names}) = {call};")
        parts = ", ".join(piece(o, f"r{i}") for i, o in enumerate(outs))
        tail.append(f"pair(ctx, vec![{parts}])")
    # What options hand back goes on the object they came in, before the answer leaves.
    finish = []
    for n, i in enumerate(f.inputs):
        if i.kind == "fit_options":
            finish.append(f"drop(x{n}); h{n}.done(&at(args, {n}))?;")
        elif i.kind == "align_options":
            finish.append(f"drop(x{n}); h{n}.done(&at(args, {n}))?;")
    body = " ".join(lines)
    if finish:
        body += " let answer = " + tail[0] + "; " + " ".join(finish) + " answer"
    else:
        body += " " + tail[0]
    return f"        {index} => {{ {body} }}"


def functions_for_glue(m):
    return [f for f in m.functions if not f.hand and not (f.c.startswith("rant_shape_from_") or f.c.startswith("rant_shape2d_from_"))]


def glue_rs(m):
    fs = functions_for_glue(m)
    arms = [arm(m, f, i) for i, f in enumerate(fs)]
    return GEN + """use rant_types::*;

use super::*;

""" + enum_impls(m) + "\n" + struct_impls(m) + """
#[allow(unused_variables)]
pub(super) fn dispatch<'js>(ctx: &Ctx<'js>, fail: &Function<'js>, trees: &Trees, index: u32, args: &[Value<'js>]) -> JsResult<Value<'js>> {
    match index {
""" + "\n".join(arms) + """
        _ => Err(fail_argument(ctx)),
    }
}
"""


SHAPES_JS = """
    const flatCopy = (list, per) => {
        if (list instanceof Float64Array) {
            if (list.length % per) throw new MathError(-1, "a list that is not in whole points");
            return list.slice();
        }
        const out = new Float64Array(list.length * per);
        for (let i = 0; i < list.length; i++) {
            out[i * per] = list[i].x;
            out[i * per + 1] = list[i].y;
            if (per === 3) out[i * per + 2] = list[i].z;
        }
        return out;
    };
"""


def prelude_js(m):
    fs = functions_for_glue(m)
    entries = []
    for i, f in enumerate(fs):
        name = camel(f.name)
        if f.name == "kdtree_create":
            entries.append(f"        {name}: (points) => new KdTree(call(fail, {i}, points)),")
        else:
            entries.append(f"        {name}: (...a) => call(fail, {i}, ...a),")
    shapes = []
    for f in m.functions:
        if not (f.c.startswith("rant_shape_from_") or f.c.startswith("rant_shape2d_from_")):
            continue
        word = f.c.split("_from_")[1]
        name = camel(f.name)
        if word in ("polyline", "polygon"):
            shapes.append(f'        {name}: (points) => ({{ kind: "{word}", value: flatCopy(points, 3) }}),')
        elif word in ("polyline2d", "polygon2d"):
            shapes.append(f'        {name}: (points) => ({{ kind: "{word}", value: flatCopy(points, 2) }}),')
        elif word == "mesh":
            shapes.append(f'        {name}: (vertices, triangles) => {{ if (triangles.length % 3) throw new MathError(-1, "triangles come in threes"); return {{ kind: "mesh", value: {{ vertices: flatCopy(vertices, 3), triangles: Uint32Array.from(triangles) }} }}; }},')
        elif word == "prism":
            shapes.append(f'        {name}: (prism) => ({{ kind: "prism", value: {{ pose: prism.pose, base: flatCopy(prism.base.points, 2), height: prism.height }} }}),')
        else:
            shapes.append(f'        {name}: (value) => ({{ kind: "{word}", value }}),')
    free = len(fs)
    return GEN + """((call) => {
    const KINDS = { [-1]: "Argument", [-2]: "Degenerate", [-3]: "Space", [-4]: "Format", [-5]: "Memory", [-6]: "Outside" };
    class MathError extends Error {
        constructor(code, text) {
            super(text);
            this.name = "MathError";
            this.code = code;
            this.kind = KINDS[code];
        }
    }
    const fail = (code, text) => new MathError(code, text);
""" + SHAPES_JS + f"""
    class KdTree {{
        constructor(id) {{ this.id = id; }}
        free() {{
            if (this.id) call(fail, {free}, this.id);
            this.id = 0;
        }}
    }}
    return {{
        MathError,
""" + "\n".join(entries + shapes) + """
    };
})
"""


def names_js(m):
    rows = []
    for f in m.functions:
        if f.hand:
            continue
        takes = []
        for i in f.inputs:
            word = camel(i.name)
            takes.append(word + "?" if i.kind in ("fit_options", "align_options", "opt_ref") else word)
        words = f.doc or f.name.replace("_", " ")
        words = words.split(". ")[0].rstrip(".")
        rows.append({"name": camel(f.name), "takes": takes, "words": words})
    body = ",\n".join("  " + json.dumps(r, separators=(", ", ": ")) for r in rows)
    return f"{GEN}// Every call of Rant Math by its name in JavaScript, for completion and hints.\nexport const NAMES = [\n{body},\n];\n"


def generate(m):
    fs = functions_for_glue(m)
    names = names_js(m)
    return [
        ("bindings/rust/src/quickjs_glue.rs", glue_rs(m)),
        ("bindings/rust/src/quickjs_prelude.js", prelude_js(m)),
        ("bindings/rust/src/quickjs_names.js", names),
        ("bindings/web/names.js", names),
    ]

# The C# binding: P/Invoke over the native library, one method per C call.
import re
import textwrap

GEN = "// Generated by tools/bindgen/gen.py from src/, do not edit.\n"

CS_SCALARS = {
    "double": "double", "float": "float", "int": "int", "int8_t": "sbyte", "uint8_t": "byte", "int16_t": "short",
    "uint16_t": "ushort", "int32_t": "int", "uint32_t": "uint", "int64_t": "long", "uint64_t": "ulong", "size_t": "ulong",
}

# A standard type that holds a managed array in C#, so a call passes a private struct of its bytes.
ALIASES = {"RantMatrix3x3": ("float", 3), "RantMatrix4x4": ("float", 4), "RantCovariance3": ("double", 3), "RantCovariance6": ("double", 6)}
RAW_STRUCTS = set(ALIASES) | {"RantCameraIntrinsics"}

KEYWORDS = {"base", "from", "to", "in", "out", "ref", "params", "fixed", "object", "string", "checked", "default", "event"}


def short(t):
    return t[4:] if t.startswith("Rant") else t


def pascal(name):
    # pose2d_apply is Pose2DApply, as the type is Pose2D.
    parts = name.split("_")
    out = ""
    for p in parts:
        p = p[0].upper() + p[1:] if p else p
        p = re.sub(r"(\d)d\b", lambda m: m.group(1) + "D", p)
        out += p
    return out


def camel(name):
    p = pascal(name)
    p = p[0].lower() + p[1:]
    return "@" + p if p in KEYWORDS else p


def cs_type(m, t):
    if t in CS_SCALARS:
        return CS_SCALARS[t]
    if t in ALIASES:
        el, n = ALIASES[t]
        return f"{el}[][]"
    return short(t)


def raw_type(m, t):
    """How a type goes across P/Invoke."""
    if t in CS_SCALARS:
        return "UIntPtr" if t == "size_t" else CS_SCALARS[t]
    if t in m.enums:
        return "int"
    if t in RAW_STRUCTS or t in VIEW_STRUCTS:
        return "Raw" + short(t)
    return short(t)


VIEW_STRUCTS = {
    "RantPolygonView", "RantPolygon2DView", "RantPolylineView", "RantPolyline2DView", "RantPathView", "RantPath2DView",
    "RantPrismView", "RantMeshView", "RantMatrixView", "RantImageView", "RantPointFieldView", "RantPointCloudView",
    "RantGridFieldView", "RantGridView", "RantLaserScanView", "RantDetection2DView", "RantDetection3DView",
    "RantFitOptions", "RantAlignOptions", "RantShape", "RantShape2D",
}


def to_raw(m, t, expr):
    if t in m.enums:
        return f"(int){expr}"
    if t in RAW_STRUCTS:
        return f"Raw{short(t)}.From({expr})"
    if t == "size_t":
        return f"(UIntPtr){expr}"
    return expr


def from_raw(m, t, expr):
    if t in m.enums:
        return f"({short(t)}){expr}"
    if t in RAW_STRUCTS:
        return f"{expr}.To()"
    if t == "size_t":
        return f"(ulong){expr}"
    return expr


def raw_structs(m):
    out = []
    for t, (el, n) in ALIASES.items():
        name = "Raw" + short(t)
        out.append(f"""    internal unsafe struct {name}
    {{
        public fixed {el} M[{n * n}];
        public static {name} From({el}[][] v)
        {{
            if (v == null || v.Length != {n}) throw new MathException(ErrorKind.Argument);
            var r = new {name}();
            for (int i = 0; i < {n}; i++)
            {{
                if (v[i] == null || v[i].Length != {n}) throw new MathException(ErrorKind.Argument);
                for (int j = 0; j < {n}; j++) r.M[i * {n} + j] = v[i][j];
            }}
            return r;
        }}
        public {el}[][] To()
        {{
            var v = new {el}[{n}][];
            for (int i = 0; i < {n}; i++)
            {{
                v[i] = new {el}[{n}];
                for (int j = 0; j < {n}; j++) v[i][j] = M[i * {n} + j];
            }}
            return v;
        }}
    }}
""")
    out.append("""    internal unsafe struct RawCameraIntrinsics
    {
        public uint Width, Height;
        public double Fx, Fy, Cx, Cy;
        public fixed double Coeffs[8];
        public ulong Model;
        public static RawCameraIntrinsics From(CameraIntrinsics v)
        {
            var r = new RawCameraIntrinsics { Width = v.Width, Height = v.Height, Fx = v.Fx, Fy = v.Fy, Cx = v.Cx, Cy = v.Cy, Model = (ulong)v.Model };
            if (v.Coeffs != null)
            {
                if (v.Coeffs.Length > 8) throw new MathException(ErrorKind.Argument);
                for (int i = 0; i < v.Coeffs.Length; i++) r.Coeffs[i] = v.Coeffs[i];
            }
            return r;
        }
        public CameraIntrinsics To()
        {
            var c = new double[8];
            for (int i = 0; i < 8; i++) c[i] = Coeffs[i];
            return new CameraIntrinsics { Width = Width, Height = Height, Fx = Fx, Fy = Fy, Cx = Cx, Cy = Cy, Coeffs = c, Model = (DistortionModel)Model };
        }
    }
""")
    for t in sorted(VIEW_STRUCTS - {"RantShape", "RantShape2D"}):
        s = m.structs[t]
        lines = []
        for f in s.fields:
            if f.pointer:
                if f.type == "char":
                    lines.append(f"        public byte* {f.name};")
                elif f.type in CS_SCALARS:
                    lines.append(f"        public {CS_SCALARS[f.type]}* {f.name};")
                else:
                    lines.append(f"        public {raw_type(m, f.type)}* {f.name};")
            elif f.type in m.enums:
                lines.append(f"        public int {f.name};")
            elif f.name == "base":
                lines.append(f"        public {raw_type(m, f.type)} @base;")
            else:
                lines.append(f"        public {raw_type(m, f.type)} {f.name};")
        out.append(f"    internal unsafe struct Raw{short(t)}\n    {{\n" + "\n".join(lines) + "\n    }\n")
    # A union's bytes. It is only made by a shape_from_ call and read by the library.
    out.append("    internal unsafe struct RawShape { public fixed long Words[11]; }\n")
    out.append("    internal unsafe struct RawShape2D { public fixed long Words[6]; }\n")
    return "\n".join(out)


def own_types(m):
    out = []
    for e in m.own_enums():
        names = e.option_names()
        out.append(f"    public enum {e.short}\n    {{\n" + "\n".join(f"        {n} = {v}," for n, (_, v) in zip(names, e.options)) + "\n    }\n")
    for s in m.own_structs():
        lines = [f"        public {cs_type(m, f.type)} {pascal(f.name)};" for f in s.fields]
        out.append(f"    [StructLayout(LayoutKind.Sequential)]\n    public struct {s.short}\n    {{\n" + "\n".join(lines) + "\n    }\n")
    return "\n".join(out)


def native_decl(m, f):
    args = []
    for p in f.params:
        t = p.type
        name = "@" + p.name if p.name in KEYWORDS else p.name
        if p.dim or p.pointer == 1:
            if t == "char":
                args.append(f"byte* {name}")
            elif t == "RantKdTree":
                args.append(f"IntPtr {name}")
            elif t in CS_SCALARS:
                args.append(f"{CS_SCALARS[t]}* {name}")
            else:
                args.append(f"{raw_type(m, t)}* {name}")
        elif p.pointer == 2:
            args.append(f"IntPtr* {name}")
        else:
            args.append(f"{raw_type(m, t)} {name}")
    ret = f.ret
    if ret == "void":
        r = "void"
    elif ret == "RantMathResult":
        r = "int"
    elif "*" in ret:
        r = "byte*" if "char" in ret else "RawPointFieldView*"
    else:
        r = raw_type(m, ret)
    return f"        [DllImport(LIB, CallingConvention = CC)] internal static extern {r} {f.c}({', '.join(args)});"


def input_decl(m, i):
    n = camel(i.name)
    k = i.kind
    if k == "value":
        return f"{cs_type(m, i.type)} {n}"
    if k == "ref":
        return f"{cs_type(m, i.type)} {n}"
    if k == "opt_ref":
        return f"{cs_type(m, i.type)}? {n} = null"
    if k == "list":
        return f"ReadOnlySpan<{cs_type(m, i.type)}> {n}"
    words = {
        "string": "string", "prism": "Prism", "shape": "Shape", "shape2d": "Shape2D", "image": "Image", "image_mut": "Image",
        "cloud": "PointCloud", "cloud_mut": "PointCloud", "grid": "Grid", "grid_mut": "Grid", "scan": "LaserScan",
        "det2d": "ReadOnlySpan<Detection2D>", "det3d": "ReadOnlySpan<Detection3D>", "matrix": "Matrix", "tree": "KdTree",
    }
    if k == "fit_options":
        return f"FitOptions {n} = null"
    if k == "align_options":
        return f"AlignOptions {n} = null"
    return f"{words[k]} {n}"


def output_type(m, o):
    k = o.kind
    if k in ("return", "out"):
        return cs_type(m, o.type)
    if k in ("fixed", "query", "sized", "same", "expr", "room"):
        return f"{cs_type(m, o.type)}[]"
    return {"matrix": "Matrix", "image": "Image", "image_copy": "Image", "cloud_layout": "PointCloud", "cloud_select": "PointCloud",
            "field": "PointField?", "prism": "Prism", "handle": "KdTree", "shape_new": short(o.type)}[k]


def result_type(m, f):
    outs = [o for o in f.outputs if o.kind != "mutated"]
    if not outs:
        return "bool" if f.errors == "bool" else "void"
    if len(outs) == 1:
        t = output_type(m, outs[0])
    else:
        t = "(" + ", ".join(f"{output_type(m, o)} {pascal(o.name) if o.name != 'return' else 'Value'}" for o in outs) + ")"
    if f.errors == "optional":
        return t if t.endswith("[]") else t + "?"
    return t


class Writer:
    def __init__(self, m, f):
        self.m, self.f = m, f
        self.pre = []      # before the fixed statements
        self.pins = []     # the fixed statements
        self.body = []     # inside them
        self.names = {id(i): camel(i.name) for i in f.inputs}
        self.using = []

    def raw_name(self, n):
        return "c_" + n.lstrip("@")

    def declare_inputs(self):
        m = self.m
        for i in self.f.inputs:
            n = self.names[id(i)]
            c = self.raw_name(n)
            k = i.kind
            if k == "list":
                t = cs_type(m, i.type)
                self.pins.append(f"fixed ({t}* {c} = {n})")
            elif k == "ref":
                self.pre.append(f"var {c} = {to_raw(m, i.type, n)};")
            elif k == "opt_ref":
                self.pre.append(f"var {c} = {n}.HasValue ? Raw{short(i.type)}.From({n}.Value) : default;")
            elif k == "prism":
                self.pins.append(f"fixed (Double2* {c}_b = {n}.Base.Points)")
                self.body.append(f"var {c} = Impl.Prism({n}, {c}_b);")
            elif k == "shape":
                self.pins.append(f"fixed (RawShape* {c} = &{n}.Raw)")
            elif k == "shape2d":
                self.pins.append(f"fixed (RawShape2D* {c} = &{n}.Raw)")
            elif k in ("image", "image_mut"):
                self.pins.append(f"fixed (byte* {c}_d = {n}.Data)")
                self.body.append(f"var {c} = Impl.Image({n}, {c}_d);")
            elif k in ("cloud", "cloud_mut"):
                self.using.append(f"var {c}_p = new CloudPin({n})")
                self.body.append(f"var {c} = {c}_p.Raw;")
            elif k in ("grid", "grid_mut"):
                self.using.append(f"var {c}_p = new GridPin({n})")
                self.body.append(f"var {c} = {c}_p.Raw;")
            elif k == "scan":
                self.pins.append(f"fixed (float* {c}_r = {n}.Ranges)")
                self.body.append(f"var {c} = Impl.Scan({n}, {c}_r);")
            elif k in ("det2d", "det3d"):
                self.using.append(f"var {c}_p = new DetectionPin({n})")
            elif k == "matrix":
                self.pins.append(f"fixed (double* {c}_d = {n}.Data)")
                self.body.append(f"var {c} = Impl.View({n}, {c}_d);")
            elif k == "string":
                self.pins.append(f"fixed (byte* {c} = Impl.Utf8({n}))")
            elif k == "fit_options":
                self.pins.append(f"fixed (double* {c}_w = {n}?.Weights)")
                self.pins.append(f"fixed (byte* {c}_i = {n}?.Inliers)")
                first = self.names[id(self.f.inputs[0])]
                self.body.append(f"var {c} = Impl.Fit({n}, {c}_w, {c}_i, {first}.Length);")
            elif k == "align_options":
                self.pins.append(f"fixed (Double3* {c}_n = {n}?.Normals)")
                self.pins.append(f"fixed (byte* {c}_i = {n}?.Inliers)")
                self.pre.append("double error = 0;")
                self.body.append(f"var {c} = Impl.Align({n}, {c}_n, {c}_i, &error, source.Length, target.Length);")

    def size_words(self, w):
        names = {i.name: self.names[id(i)] for i in self.f.inputs}
        if w == "min":
            return "System.Math.Min(a.Rows, a.Cols)"
        if w == "degree + 1":
            return "degree + 1"
        return w.replace(".rows", ".Rows").replace(".cols", ".Cols")

    def image_word(self, w):
        return {
            "src.format": "src.Format", "src.width": "src.Width", "src.height": "src.Height",
            "turned_width": "((quarterTurns % 4 + 4) % 4 & 1) != 0 ? src.Height : src.Width",
            "turned_height": "((quarterTurns % 4 + 4) % 4 & 1) != 0 ? src.Width : src.Height",
            "ideal_width": "(ideal ?? camera).Width",
            "ideal_height": "(ideal ?? camera).Height",
        }.get(w, w)

    def declare_outputs(self):
        m = self.m
        for j, o in enumerate(self.f.outputs):
            k = o.kind
            name = f"o{j}"
            if k == "out":
                self.pre.append(f"{raw_type(m, o.type)} {name} = default;")
            elif k in ("fixed", "same", "sized", "expr", "room"):
                t = cs_type(m, o.type)
                if k == "fixed":
                    size = str(o.size)
                elif k == "same":
                    size = f"{self.names[id(o.size)]}.Length"
                elif k in ("sized", "room"):
                    size = self.names[id(o.size)]
                else:
                    size = self.size_words(o.size)
                self.pre.append(f"var {name} = new {t}[{size}];")
                self.pins.append(f"fixed ({raw_type(m, o.type)}* p{j} = {name})")
            elif k == "matrix":
                self.pre.append(f"var {name} = Impl.NewMatrix({self.size_words(o.rows)}, {self.size_words(o.cols)});")
                self.pins.append(f"fixed (double* p{j} = {name}.Data)")
            elif k == "image":
                self.pre.append(f"var {name} = Impl.NewImage({self.image_word(o.size)}, {self.image_word(o.cols)}, {self.image_word(o.rows)});")
                self.pins.append(f"fixed (byte* p{j} = {name}.Data)")
                self.body.append(f"var c{j} = Impl.Image({name}, p{j});")
            elif k == "image_copy":
                self.pre.append(f"RawImageView {name} = default;")
            elif k == "handle":
                self.pre.append("IntPtr tree = IntPtr.Zero;")

    def c_arg(self, a, asking):
        k = a.kind
        m = self.m
        n = self.names.get(id(a.a), "")
        c = self.raw_name(n) if n else ""
        if k == "value":
            return to_raw(m, a.a.type, n)
        if k == "ref":
            return f"&{c}"
        if k == "opt_ref":
            return f"{n}.HasValue ? &{c} : null"
        if k == "list_ptr":
            return c
        if k == "list_count":
            if a.b:
                return f"Impl.Same({n}.Length, {self.names[id(a.b)]}.Length)"
            return f"(uint){n}.Length"
        if k == "degree":
            return f"(uint)({n}.Length - 1)"
        if k == "view":
            word = m.structs[a.b].fields[0].name
            return f"new Raw{short(a.b)} {{ {word} = {c}, count = (uint){n}.Length }}"
        if k == "mesh":
            other = self.names[id(a.b)]
            return f"Impl.Mesh({c}, {n}.Length, {self.raw_name(other)}, {other}.Length)"
        if k == "prism":
            return c
        if k == "shape" or k == "shape2d":
            return c
        if k in ("image", "image_mut", "cloud", "cloud_mut", "grid", "grid_mut", "scan"):
            return f"&{c}"
        if k == "matrix":
            return c
        if k == "fit_options" or k == "align_options":
            return f"{n} == null ? null : &{c}"
        if k == "det_ptr":
            return f"({'RawDetection2DView' if a.a.kind == 'det2d' else 'RawDetection3DView'}*){c}_p.Items"
        if k == "det_count":
            return f"(uint){n}.Length"
        if k == "string":
            return c
        if k == "tree":
            return f"{n}.Handle"
        if k == "out":
            o = a.a
            j = self.f.outputs.index(o)
            if o.kind == "handle":
                return "&tree"
            if o.kind in ("out", "image_copy"):
                return f"&o{j}"
            if o.kind == "query" and asking:
                return "null"
            return f"p{j}"
        if k == "count_ptr":
            o = a.a
            return "&n0" if o.kind == "room" else f"&n{self.f.outputs.index(o)}"
        if k == "matrix_out":
            j = self.f.outputs.index(a.a)
            return f"new RawMatrixView {{ data = p{j}, rows = o{j}.Rows, cols = o{j}.Cols }}"
        if k == "image_out":
            return f"&c{self.f.outputs.index(a.a)}"
        raise KeyError(k)

    def call(self, asking=False):
        return f"Native.{self.f.c}({', '.join(self.c_arg(a, asking) for a in self.f.args)})"

    def answer_of(self, o, j):
        m = self.m
        k = o.kind
        if k == "return":
            return from_raw(m, o.type, "r")
        if k == "out":
            return from_raw(m, o.type, f"o{j}")
        if k in ("fixed", "same", "sized", "expr", "room", "query", "matrix", "image"):
            return f"o{j}"
        if k == "image_copy":
            return f"Impl.CopyImage(o{j})"
        if k == "handle":
            return "new KdTree(tree)"
        if k == "prism":
            return "Impl.PrismOf(r)"
        if k == "cloud_layout":
            return "Impl.CloudLike(r)"
        raise KeyError(k)

    def generate(self):
        f = self.f
        if f.c.startswith("rant_shape_from_") or f.c.startswith("rant_shape2d_from_"):
            return self.shape_body()
        if f.c == "rant_point_cloud_field":
            return ["using (var p = new CloudPin(cloud))", "fixed (byte* s = Impl.Utf8(name))", "{", "    var c = p.Raw;",
                    "    var found = Native.rant_point_cloud_field(&c, s);", "    return found == null ? (PointField?)null : Impl.Field(*found);", "}"]
        if f.c == "rant_point_cloud_select":
            return ["using (var p = new CloudPin(cloud))", "fixed (byte* k = keep)", "{", "    var c = p.Raw;",
                    "    Impl.Check(Native.rant_point_cloud_check(&c));",
                    "    if ((ulong)keep.Length != (ulong)c.size / c.point_step) throw new MathException(ErrorKind.Argument);",
                    "    uint n = 0;", "    Impl.Room(Native.rant_point_cloud_select(&c, k, null, &n));",
                    "    var data = new byte[(int)n * (int)c.point_step];", "    fixed (byte* d = data) Impl.Check(Native.rant_point_cloud_select(&c, k, d, &n));",
                    "    var r = Impl.CloudLike(c);", "    r.Data = data;", "    return r;", "}"]
        self.declare_inputs()
        self.declare_outputs()
        if f.c == "rant_polynomial_at":
            self.pre.append("if (coefficients.Length == 0) throw new MathException(ErrorKind.Argument);")
        asked = [o for o in f.outputs if o.kind == "query" and not hasattr(o.size, "kind")]
        rooms = [o for o in f.outputs if o.kind == "room"]
        lines = []
        answers = [self.answer_of(o, j) for j, o in enumerate(f.outputs) if o.kind != "mutated"]
        if len(answers) > 1:
            answer = "(" + ", ".join(answers) + ")"
        else:
            answer = answers[0] if answers else None
        if asked:
            for o in asked:
                lines.append(f"uint n{f.outputs.index(o)} = 0;")
            lines.append(f"Impl.Room({self.call(True)});")
            nest = []
            for j, o in enumerate(f.outputs):
                if o.kind == "query":
                    who = f.outputs.index(o.size) if hasattr(o.size, "kind") else j
                    per = f" * {o.per}" if o.per != 1 else ""
                    t = cs_type(self.m, o.type)
                    lines.append(f"var o{j} = new {t}[(int)n{who}{per}];")
                    nest.append(f"fixed ({raw_type(self.m, o.type)}* p{j} = o{j})")
            for pin in nest:
                lines.append(pin)
            lines.append("{")
            lines.append(f"    Impl.Check({self.call()});")
            for j, o in enumerate(f.outputs):
                if o.kind == "query":
                    who = f.outputs.index(o.size) if hasattr(o.size, "kind") else j
                    per = f" * {o.per}" if o.per != 1 else ""
                    lines.append(f"    Array.Resize(ref o{j}, (int)n{who}{per});")
            lines.append(f"    return {answer};")
            lines.append("}")
        else:
            if rooms:
                lines.append(f"uint n0 = {self.names[id(rooms[0].size)]};")
            call = self.call()
            if f.ret == "RantMathResult":
                lines.append(f"Impl.Check({call});")
            elif f.ret == "int":
                if f.outputs:
                    lines.append(f"if ({call} == 0) return null;")
                else:
                    lines.append(f"return {call} != 0;")
            elif f.ret == "void":
                lines.append(f"{call};")
            else:
                lines.append(f"var r = {call};")
            for j, o in enumerate(f.outputs):
                if o.kind == "room":
                    lines.append(f"Array.Resize(ref o{j}, (int)n0);")
            for i in f.inputs:
                if i.kind == "align_options":
                    lines.append(f"if ({self.names[id(i)]} != null) {self.names[id(i)]}.Error = error;")
            if answer:
                lines.append(f"return {answer};")
        out = list(self.pre)
        out += [f"using ({u})" for u in self.using]
        out += self.pins
        if self.pins or self.using:
            out.append("{")
            out += ["    " + x for x in self.body + lines]
            out.append("}")
        else:
            out += self.body + lines
        for u in self.using:
            pass
        return out

    def shape_body(self):
        f = self.f
        word = f.c.split("_from_")[1]
        i = f.inputs[0]
        n = self.names[id(i)]
        two = f.ret == "RantShape2D"
        cls = "Shape2D" if two else "Shape"
        if word in ("polyline", "polygon", "polyline2d", "polygon2d"):
            view = {"polyline": "RawPolylineView", "polygon": "RawPolygonView", "polyline2d": "RawPolyline2DView", "polygon2d": "RawPolygon2DView"}[word]
            el = cs_type(self.m, i.type)
            return [f"var block = Impl.Copy({n});",
                    f"return new {cls}(Native.{f.c}(new {view} {{ points = ({el}*)block, count = (uint){n}.Length }}), block);"]
        if word == "mesh":
            return ["var v = Impl.Copy(vertices);", "var t = Impl.Copy(triangles);",
                    "var m = Impl.Mesh((Double3*)v, vertices.Length, (uint*)t, triangles.Length);",
                    "return new Shape(Native.rant_shape_from_mesh(m), v, t);"]
        if word == "prism":
            return ["var b = Impl.Copy<Double2>(prism.Base.Points);",
                    "var c = Impl.Prism(prism, (Double2*)b);",
                    "return new Shape(Native.rant_shape_from_prism(c), b);"]
        return [f"return new {cls}(Native.{f.c}({to_raw(self.m, i.type, n)}));"]


def function(m, f):
    w = Writer(m, f)
    body = w.generate()
    # An argument after an optional one must be optional too, so optional ones come last here.
    args = [input_decl(m, i) for i in f.inputs]
    required = [a for a in args if " = null" not in a]
    optional = [a for a in args if " = null" in a]
    doc = ""
    if f.doc:
        wrapped = textwrap.wrap(f.doc.replace("&", "and").replace("<", "under").replace(">", "over"), 96)
        doc = "        /// <summary>" + "\n        /// ".join(wrapped) + "</summary>\n"
    head = f"        public static unsafe {result_type(m, f)} {pascal(f.name)}({', '.join(required + optional)})\n        {{\n"
    return doc + head + "\n".join("            " + line for line in body) + "\n        }\n"


def api(m):
    natives = [native_decl(m, f) for f in m.functions if not f.hand]
    functions = [function(m, f) for f in m.functions if not f.hand]
    return (GEN + """using System;
using System.Runtime.InteropServices;
using Rant.Types;

#pragma warning disable CS1591

namespace Rant.Math
{
""" + own_types(m) + "\n" + raw_structs(m) + """
    internal static unsafe partial class Native
    {
""" + "\n".join(natives) + """
    }

    /// <summary>Every call of Rant Math, on the standard types. A failure throws MathException.</summary>
    public static partial class RantMath
    {
""" + "\n".join(functions) + """    }
}
""")


# The vector test: a thunk per function, reading JSON into inputs and handing the answer back.

def thunk_input(m, i, n):
    k = i.kind
    a = f"a[{n}]"
    t = cs_type(m, i.type) if i.type else ""
    if k in ("value", "ref"):
        if i.type in ALIASES:
            return f"var x{n} = J.To<{t}>({a}.GetProperty(\"m\"));"
        if i.type in m.enums:
            return f"var x{n} = ({t})J.To<int>({a});"
        return f"var x{n} = J.To<{t}>({a});"
    if k == "opt_ref":
        return f"{t}? x{n} = {a}.ValueKind == System.Text.Json.JsonValueKind.Null ? ({t}?)null : J.To<{t}>({a});"
    if k == "list":
        return f"var x{n} = J.To<{t}[]>({a});"
    return {
        "string": f"var x{n} = {a}.GetString();",
        "prism": f"var x{n} = J.ToPrism({a});",
        "shape": f"var x{n} = J.ToShape({a});",
        "shape2d": f"var x{n} = J.ToShape2D({a});",
        "image": f"var x{n} = J.ToImage({a});",
        "image_mut": f"var x{n} = J.ToImage({a});",
        "cloud": f"var x{n} = J.ToCloud({a});",
        "cloud_mut": f"var x{n} = J.ToCloud({a});",
        "grid": f"var x{n} = J.ToGrid({a});",
        "grid_mut": f"var x{n} = J.ToGrid({a});",
        "scan": f"var x{n} = J.ToScan({a});",
        "det2d": f"var x{n} = J.ToDet2D({a});",
        "det3d": f"var x{n} = J.ToDet3D({a});",
        "matrix": f"var x{n} = J.ToMatrix({a});",
        "fit_options": f"var x{n} = J.ToFit({a}, a[0].GetArrayLength());",
        "align_options": f"var x{n} = J.ToAlign({a}, a[0].GetArrayLength());",
        "tree": f"using var x{n} = RantMath.KdtreeCreate(J.To<Double3[]>({a}.GetProperty(\"points\")));",
    }[k]


def thunks(m):
    rows = [GEN, "using System;", "using System.Collections.Generic;", "using Rant.Types;", "using Rant.Math;", "",
            "static partial class Thunks", "{", "    public static readonly Dictionary<string, Func<System.Text.Json.JsonElement[], Answer>> Table = new()", "    {"]
    for f in m.functions:
        if not f.vector:
            continue
        lines = [thunk_input(m, i, n) for n, i in enumerate(f.inputs)]
        # The call's optional inputs come last, so its arguments are in that order.
        order = [n for n, i in enumerate(f.inputs) if i.kind not in ("fit_options", "align_options", "opt_ref")]
        order += [n for n, i in enumerate(f.inputs) if i.kind in ("fit_options", "align_options", "opt_ref")]
        args = ", ".join(f"x{n}" for n in order)
        call = f"RantMath.{pascal(f.name)}({args})"
        mutated = [o for o in f.outputs if o.kind == "mutated"]
        outs = [o for o in f.outputs if o.kind != "mutated"]
        wrap = [o.type in ALIASES for o in outs]
        if mutated:
            lines.append(f"{call};")
            lines.append(f"var answer = new Answer(x{f.inputs.index(mutated[0].size)});")
        elif not outs and f.errors != "bool":
            lines.append(f"{call};")
            lines.append("var answer = new Answer(null);")
        elif any(wrap) and len(outs) == 1:
            lines.append(f"var answer = new Answer(new Dictionary<string, object> {{ [\"m\"] = {call} }});")
        else:
            lines.append(f"var answer = new Answer({call});")
        for n, i in enumerate(f.inputs):
            if i.kind in ("fit_options", "align_options"):
                lines.append(f"J.Extras(answer, x{n});")
        rows.append(f'        ["{f.name}"] = a => {{ ' + " ".join(lines) + " return answer; },")
    rows += ["    };", "}", ""]
    return "\n".join(rows)


def generate(m):
    return [
        ("bindings/csharp/RantMath.g.cs", api(m)),
        ("tests/bindings/generated/CSharpThunks.g.cs", thunks(m)),
    ]

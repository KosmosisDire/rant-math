"""Writes src/colormaps.c, matplotlib's colormap tables as rounded sRGB bytes.
Run with python tools/colormaps.py. The output is committed so a build needs no Python."""
import os

import matplotlib
import numpy as np

# The order of RantColormap after GRAY, which needs no table.
MAPS = ["viridis", "plasma", "inferno", "magma", "turbo"]

rows = []
for name in MAPS:
    lut = np.asarray(matplotlib.colormaps[name].colors, dtype=float)
    assert lut.shape == (256, 3), name
    b = np.floor(lut * 255.0 + 0.5).astype(int)
    lines = ",\n".join("        " + ", ".join(f"{{{r}, {g}, {bl}}}" for r, g, bl in b[i:i + 6]) for i in range(0, 256, 6))
    rows.append(f"    /* {name} */\n    {{\n{lines}\n    }}")

here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "..", "src", "colormaps.c"), "w", newline="\n") as f:
    f.write("/* GENERATED by tools/colormaps.py. viridis, plasma, inferno, magma: CC0, Nathaniel Smith and\n")
    f.write(" * Stefan van der Walt. turbo: Copyright 2019 Google LLC, Apache License 2.0, licenses/turbo-apache-2.0.txt. */\n")
    f.write('#include "internal.h"\n\n')
    f.write(f"const uint8_t i_math_colormaps[{len(MAPS)}][256][3] = {{\n")
    f.write(",\n".join(rows))
    f.write("\n};\n")
print("wrote src/colormaps.c")
